/**
 * 把手感輪廓套在一份 spec 上，回傳新的 spec。**不修改傳入的物件。**
 *
 * 倍率為 1 時原封不動回傳**同一個物件** —— 這讓「史實測試跑在未經包裝的
 * spec 上」可以用同一性斷言守住，而不是靠讀者自律。
 */
export function applyFeel(spec: AircraftSpec, feel: FeelProfile): AircraftSpec {
  if (
    feel.roll === 1 && feel.oswald === 1 && feel.power === 1
    && feel.lift === 1 && feel.cd0 === 1
  ) return spec
  // 【逐項判斷而不是一律複製】沒有被這一項動到的子結構要維持**同一個物件**，
  // 那是「這個倍率只碰它該碰的東西」唯一測得到的形式。
  const moments = feel.roll === 1
    ? spec.moments
    : { ...spec.moments, clDa: spec.moments.clDa * feel.roll }
  const wing = feel.oswald === 1
    ? spec.wing
    : { ...spec.wing, oswald: spec.wing.oswald * feel.oswald }
  const engine = feel.power === 1
    ? spec.engine
    : {
      ...spec.engine,
      gears: spec.engine.gears.map((g) => ({
        ...g,
        powerSeaLevel: g.powerSeaLevel * feel.power,
        powerCritical: g.powerCritical * feel.power,
      })),
    }
  const lift = feel.lift === 1
    ? spec.lift
    : { ...spec.lift, clAlpha: spec.lift.clAlpha * feel.lift }
  const drag = feel.cd0 === 1
    ? spec.drag
    : { ...spec.drag, cd0: spec.drag.cd0 * feel.cd0 }
  return { ...spec, moments, wing, engine, lift, drag }
}
