import type { AircraftSpec } from './types'

/**
 * 手感係數：把「史實的飛機」與「玩起來的飛機」分成兩層。
 *
 * 【為什麼需要這一層】`src/specs/*.ts` 的每一個數字都對應真飛機，而
 * `test/performance/historical.test.ts` 的整層 L2 斷言（極速／失速／升限
 * ±5%、海平面爬升率 [−15%, −12%]）就是靠這個前提才有意義。直接去改 spec
 * 換手感，等於讓那層測試從此變成「符合我們亂調的數字」——它會照樣是綠的，
 * 卻不再守著任何東西。
 *
 * 所以手感調整走這裡：**史實值原封不動，遊戲執行時套一層倍率。**
 * `HISTORICAL`（全部 1.0）是那層測試永遠使用的輪廓。
 *
 * 【只放真的會動的旋鈕】不預先開一堆倍率欄位。每一項都要先評估代價
 * （見下方各欄位的註解）。
 *
 * ---
 *
 * # 遊戲裡的飛機**刻意不是史實飛機**（2026-08-07 專案負責人裁定）
 *
 * `GAME_FEEL` 出貨的 P-51D 爬升率是史實的 2.2 倍、持續迴旋率 1.9 倍。
 * 這是**明確的取捨，不是失誤**。原始的判斷是：
 *
 * > 「這個遊戲對於能量太過於寫實了，導致遊戲性很差（例如爬升很慢、
 * > 閃躲掉能量）。」
 *
 * 史實值原封不動留在 `specs/*.ts`，`historical.test.ts` 跑的是**沒有包裝
 * 的 spec**，所以那一層照樣守著真飛機。這個檔案是兩者之間唯一的閘門。
 *
 * ## 怎麼重新調（未來要改的人看這裡）
 *
 * 五個倍率不是獨立的，它們透過三條物理關係耦合。照這個順序調：
 *
 * 1. **先定極速**：高速平飛時誘導阻力可忽略，`V_max³ ∝ power / cd0`。
 *    所以 `power` 與 `cd0` **同倍率**一起動時極速不變。要改極速就打破
 *    這個比值，不要單獨動其中一個然後回頭修另一個。
 * 2. **再定失速／角落速度／瞬間迴旋**：這三個只由 `lift` 決定，與上面
 *    完全解耦。角落速度 = 「能拉滿 G 的最低速度」，它決定玩家在常態
 *    速度下轉不轉得動 —— 手感上比瞬間迴旋率本身更重要。
 * 3. **最後定持續迴旋**：由 `power` 與 `oswald` 一起決定。固定極速之後，
 *    `oswald` 與 `power` 之間還有一個自由度，而它換到的是
 *    **爬升 ↔ 俯衝保速**：`oswald` 高、`power` 低 → 俯衝保速好、爬升差；
 *    反之亦然。出貨值取 `oswald` 2.0（見 `cd0` 註解裡的整張表）。
 * 4. `roll` 獨立於以上全部，只影響操作反應速度。
 *
 * ## 調完之後必須一起回頭看的東西
 *
 * - **AI 的能量判準**：`steer.ts` 的 `brakeCornerRatio`、`unloadMargin`、
 *   `speedRecoverMargin`、`extendPitchAngle` 的兩個增益，全是照**舊包絡**
 *   調出來的。**2026-08-07 已全部重掃並結案**，結論是「來歷過期，值沒壞」
 *   —— 那些判準寫的都是**比值**（TAS ÷ 失速速度、TAS ÷ 角落速度），分母
 *   是飛機自己的氣動性能，倍率一動分母同步跟著走。`ai-manoeuvre` 五條指標
 *   沒有一條接近門檻，三條還變好。五個旋鈕裡只有 `brakeCornerRatio` 真的
 *   該動（1.6 → 1.8，高能量開局由「200 秒打不完、自己挨 428」變成
 *   「156 秒擊落、毫髮無傷」）。掃描表在 `steer.ts` 各欄位的註解裡，完整
 *   推論見 `docs/superpowers/specs/2026-08-07-ai-energy-recalibration-design.md`。
 *   **下次再調倍率時仍然要回頭看這一項** —— 結論是「這一次沒壞」，不是
 *   「這一層不受影響」。
 * - **目標選擇的 `turnTimeScale`**：`turnTime = 角度 ÷ 瞬間迴旋率`，飛機
 *   轉得快之後「掉頭去追後方」變便宜。實測 `rearShare` 因此由 25.6% 升到
 *   31.6%，`ai-targeting.test.ts` 的門檻已隨之重新定值（見該檔註解）。
 * - **指揮儀的方向舵瞄準輔助**：`betaFadeStart`/`betaMax`（6°/10°）是照
 *   側滑中位 1.44° 訂的；現在中位 6.80°，p10 的輔助權限由 0.94 掉到 0.51。
 *   小角度準星微調會變鈍。實測**不是**舵權不足（`cnDr` ×2 無效），是那個
 *   淡出區間過期了。2026-08-07 試飛後判定手感可接受，暫不處理。
 */
export interface FeelProfile {
  /**
   * 滾轉權限倍率。1 = 史實。
   *
   * 實作方式是縮放 `moments.clDa`（副翼滾轉力矩導數）。滿舵穩態滾轉率
   * `p = (clDa / −clP)·(2V/b)` 對 `clDa` 是線性的，所以倍率就是滾轉率倍率；
   * `FlightDirector.steadyRollRate` 讀的是同一個導數，指揮儀的內部估計會
   * 自動跟上，不會出現「飛機滾得比指揮儀以為的快」的錯配。
   *
   * 【為什麼滾轉是第一個被允許動的】滾轉率不進任何史實斷言的判準
   * （`relative.test.ts` 量的是**兩機的比值**，一起縮放不變），而且滾轉與
   * 能量無關 —— 副翼不吃升力配平。所以它是唯一「動了也還是那台 P-51」的
   * 旋鈕。當時同時記錄了推力不能動的理由：它會同時推動極速、爬升率、升限
   * 與極速峰值高度四項，實測 +20% 讓 P-51 的臨界高度極速由 +3.83% 變成
   * 約 +10%、海平面爬升率由 −14.45% 變成約 0%，四項全部出界。
   *
   * 【那條理由在 2026-08-07 被專案負責人推翻了】見檔案頂端的「非史實」
   * 宣告：現在 `power` 與 `cd0` 都在動，遊戲飛機刻意不再是史實 P-51。
   * 上面那段實測沒有失效 —— 它描述的後果**正是現在接受的代價**。
   */
  roll: number
  /**
   * 誘導阻力的**效率**倍率。1 = 史實。實作方式是縮放 `wing.oswald`，
   * 而 `inducedDragFactor = 1/(π·oswald·AR)`，所以倍率 1.5 = 誘導阻力 ÷1.5。
   *
   * 【為什麼是這一項而不是 cd0 或推力】阻力模型是 `CD = cd0 + k·CL²`，
   * 而兩項各自主宰完全不同的區域。實算 P-51D 的誘導阻力佔總阻力：
   *
   * ```
   *   巡航平飛  CL 0.12    5%
   *   最佳爬升  CL 0.62   59%
   *   硬破防    CL 1.45   89%
   * ```
   *
   * 「拉桿的代價」幾乎**全部**是誘導阻力。三個候選旋鈕的實算對照：
   *
   * ```
   *                        巡航總阻力  爬升總阻力  硬破防總阻力
   *   cd0 砍半（寄生阻力）     −48%       −20%        −6%
   *   oswald ×1.5（本項）      −2%       −19%       −29%
   *   oswald ×2.3             −3%       −33%       −50%
   * ```
   *
   * 砍 `cd0` 對閃躲幾乎無效（−6%）卻會讓極速暴增。提高推力則把 Ps 全域
   * 抬高，極速／爬升率／升限／臨界高度四項一起動，而且同樣沒有特別針對
   * 拉桿的代價。**`oswald` 是唯一同時打中「爬升慢」與「閃躲掉能量」而
   * 極速不動的旋鈕**，所以它是三個之中第一個上線的。
   *
   * 【後來 `power` 與 `cd0` 也上線了，不衝突】上面那段是「單獨動一項」的
   * 比較。`cd0` 單獨**放大**（不是砍半）配上同倍率的 `power` 可以鎖住極速
   * ——那是三項一起用時才出現的自由度，見 `cd0` 的註解。
   *
   * 【它會動到什麼】爬升率與升限（`p51d.ts` 的註解記錄過 oswald 0.75→0.88
   * 讓升限 +400 m、爬升率 +2.8%），以及角落速度與持續轉彎率 —— 後兩者正是
   * 目的。極速由 `cd0` 與推力決定，不受影響。
   *
   * 【為什麼超過 1.0 也合法】`oswald` 在物理上是效率係數，恆 ≤ 1。倍率把它
   * 推過 1 是**明確的遊戲化**，這正是它該待在 `feel.ts` 而不是 `p51d.ts` 的
   * 理由 —— 史實值原封不動，史實測試跑的是沒包裝的 spec。
   */
  oswald: number
  /**
   * 發動機功率倍率。1 = 史實。縮放每一段增壓級的 `powerSeaLevel` 與
   * `powerCritical`，比值不變，所以臨界高度與換檔點的形狀維持原樣。
   *
   * 【它買到什麼】爬升率與**持續**迴旋率 —— 兩者都由比余功率
   * `Ps = V(T−D)/W` 決定，而推力是那條式子裡唯一能整體抬高的項。
   * 下表是**第一輪掃描的原始紀錄**（當時 `oswald` 1.5、`cd0` 尚未存在），
   * 保留是為了顯示「`power` 單獨動時極速跟著跑」這個關係；出貨值不在表內，
   * 它是後來與 `cd0`、`oswald` 一起解出來的（見 `cd0` 註解）：
   *
   * ```
   *          海平面爬升 m/min   4000m 極速 km/h   升限 m   持續迴旋 °/s
   *   ×1.0        955               704          13168        16.1
   *   ×1.2       1199               745          13898        17.6
   *   ×1.4       1447               782          14507        18.8
   *   ×1.6       1696               814          15029        19.9
   * ```
   *
   * 【代價】極速、升限、極速峰值高度一起跑掉 —— 這是推力的本質，
   * 不是實作缺陷。`roll` 的註解記錄過同一件事（+20% 讓四項全部出界）。
   * **瞬間**迴旋率完全不動：那由 CLmax 與結構過載決定，與推力無關。
   */
  power: number
  /**
   * 升力曲線斜率倍率。1 = 史實。實作方式是縮放 `lift.clAlpha`。
   *
   * 【為什麼動 `clAlpha` 而不是 `clMax`】`AircraftSpec.clMax` 這個欄位
   * **沒有任何程式碼在讀**（`grep '\.clMax' src/` 除了 `derivedClMax` 之外
   * 為空）。真正生效的是推導值 `derivedClMax = clAlpha·(alphaCrit − alphaZero)`，
   * 所以要動 CLmax 只能動 `clAlpha` 或 `alphaCrit`。取前者是因為 `alphaCrit`
   * 同時是失速混合區（`stallBlend`）的參考點，動它會連帶改變失速的手感曲線。
   *
   * 【它買到什麼】瞬間迴旋率，而且**把角落速度拉下來** —— 後者才是重點。
   * 角落速度是「能拉滿 G 的最低速度」，史實值 159 m/s（572 km/h）高於空戰
   * 的常態速度，於是大部分時間都拉不到極限。實算 @4000 m：
   *
   * ```
   *          失速 m/s   角落速度 m/s      瞬間迴旋 °/s   持續迴旋 °/s
   *   ×1.0      56       159 (572 km/h)      28.1          16.1
   *   ×1.2      51       145 (522 km/h)      30.8          17.0
   *   ×1.3      49       139 (500 km/h)      32.0          17.6
   *   ×1.4      47       134 (482 km/h)      33.2          17.6
   * ```
   *
   * 爬升、極速、升限**完全不動**。
   *
   * 【代價】失速速度跟著下降，飛機變得難以失速 —— 操作的技術門檻降低。
   *
   * 【為什麼不用結構過載上限】`limits.gPositive` 也能買瞬間迴旋，但它讓
   * 角落速度**上升**（×1.25 → 177 m/s、×1.5 → 194 m/s），與「在常態速度
   * 下轉得動」的目的相反。實測後排除。
   */
  lift: number
  /**
   * 寄生阻力倍率。1 = 史實。縮放 `drag.cd0`。
   *
   * 【它單獨存在沒有意義，它的用途是綁住極速】高速平飛時 CL 很小、誘導阻力
   * 可以忽略，於是推力 = 寄生阻力給出
   *
   * ```
   *   P·η/V = ½ρV²S·cd0   →   V_max³ ∝ P / cd0
   * ```
   *
   * **極速只由這個比值決定**。所以 `power` 與 `cd0` 同倍率一起放大時極速
   * 完全不動，而爬升與迴旋照樣受益 —— 因為那兩者發生在低速／高 CL，那裡
   * 誘導阻力才是主角，`cd0` 的權重小得多。實算 P-51D（`lift` 1.3 固定，
   * 每一列的 `cd0` 都是解出來讓 4000 m 極速 = 史實 699 km/h 的值）：
   *
   * ```
   *   oswald  power   cd0    爬升 m/min   持續迴旋 °/s   俯衝極速 km/h
   *     1.5    2.63   2.75      2658          25.0           974
   *     2.0    1.98   2.06      1993          25.0          1001   ← 出貨
   *     2.5    1.58   1.65      1595          25.0          1023
   *     3.0    1.32   1.38      1329          25.0          1042
   *   （史實）  1      1          907          13.4          1079
   * ```
   *
   * 【族內唯一的自由度是「爬升 ↔ 俯衝極速」】四列的極速、失速、角落速度、
   * 瞬間迴旋、持續迴旋**完全相同**。`cd0` 拉得越高，換到的爬升越多，
   * 但俯衝終端速度掉得越多 —— 因為俯衝時沒有 G、CL 極小，阻力幾乎全是寄生。
   *
   * 【要注意的手感副作用】`cd0` ×2 表示收油門或拉 G 之後**掉速快一倍**。
   * 速度會變得非常「油門相依」，能量交換的節奏跟史實不一樣。
   */
  cd0: number
}

