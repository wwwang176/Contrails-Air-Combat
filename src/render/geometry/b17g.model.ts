/**
 * B-17G Flying Fortress 的 GLB 外型 —— 真機全長 22.66 m、翼展 31.62 m、
 * 每具三葉槳直徑 3.53 m。
 *
 * **來源是 `tools/blender/build_b17.py`**：在 Blender 裡對著
 * `ref/1943_boeing_b-17g-60-ve_flying_fortress.glb` 直接量、直接 loft，與
 * A6M5 v3／Ki-84／F4F-4／F6F-5 同一條路。**13,251 三角形**（程式版那一支是 19,458）。
 *
 * 座標是機體座標：X 翼展、Y 上、Z 機尾，原點在主翼四分之一弦線
 * （由乾淨段 x 4.6／8.0 外推，翼根弦 6.024 對 `b17g.hull.ts` 的 6.018）。
 *
 * ── 尾錐要收成鈍圓、槳轂要有鼻子、發動機艙的表要平滑 ─────────
 *
 * **尾錐**：參考模型在機體 z 16.35 結束時剖面還有 0.33 × 0.385 —— 那是一個鈍口，
 * 不是收斂到一點。所以尾端**不用 fan 收尾**（fan 是整圈接到一個極點，由後方看
 * 是一個點而不是一圈），改成再補一環（最後一站的環照中心縮 0.55）然後封蓋。
 * 站位也要挑量得到的：−16.32 的 `station()` 回傳 None，那一站會被無聲丟掉，
 * 尾端於是又變回「16.20 的環直接扇到點」；16.26 量得到。末端往後挪要**同時改
 * 命中盒**（`src/specs/b17g.ts` 的「補漏 6」）。
 *
 * **槳轂**：參考模型量到由槳葉平面往前 0.14 起、半徑 0.15，到 +0.46 收成一點。
 * **軸桿要一路接回整流罩** —— 只做槳葉平面往前那一段，鼻子與罩子之間空著 0.18，
 * 而槳葉根部本來就是空心的（葉片由半徑 0.15 起算），側面看就是一顆浮在空中的
 * 錐體。參考模型在外側發動機（軸心 x −6.57、高度 0.257）量到的是連續的：整流罩
 * 收在 y 2.57（半徑 0.66），接著 2.60…3.17 一段半徑 0.10…0.147 的軸桿，槳葉平面
 * 2.75 就在那一段中間。所以基環放在罩子鼻端再往內 0.04（內外側都是 dz −0.22）。
 * `B17_SpinnerN` **不能取名 `B17_PropN`** —— `glb.ts` 的 isNamed 認「名字 + 可有
 * 可無的分隔符 + 數字」，取那個名字就會被歸進轉軸底下，`multi-engine-glb.test.ts`
 * 檢查「每一具正好三片槳葉」那一格會讀到 4。
 *
 * **發動機艙**：`build_b17.py` 那兩張剖面表（沿用第一代逐站量的值）帶著噪聲 ——
 * 中心高度抖 ±0.03、半寬的二階差不規則。艙身只有 0.78 半徑，平面著色下每一環的法線跟著交替，
 * 看起來就是一條一條的。沿 z 做保邊拉普拉斯（門檻 0.04，唇口那一階 0.053 不動）。
 *
 * ── 座艙玻璃：逐片照參考模型量，全部是平面 ──────────────────
 *
 * **第一代的結論「座艙那一段連凹進去的玻璃都沒有」是錯的。** 把參考模型的透明件
 * `Object_50` 拆連通塊，座艙那一段有六片，每一片的 PCA 殘差都 ≤ 0.009：
 *
 * ```
 *   片      x           機體 z         高度         法線
 *   風擋    0.03…0.66   −3.21…−2.59   1.48…1.81   (0.52, 0.64, 0.57)
 *   側窗前  0.60…0.69   −2.76…−1.92   1.45…1.81   (0.97, 0.01, 0.26)
 *   側窗後  0.60…0.69   −1.85…−1.42   1.48…1.82   (0.97, 0.00, 0.25)
 *   頂窗    0.21…0.52   −2.76…−2.22   1.89…1.96   (0.17, 0.05, 0.98)
 *   頰窗    1.04…1.13   −3.92…−3.55   0.42…0.71   (0.98, 0.11, 0.16)
 * ```
 *
 * 機背上還有兩處，殘差 0.02…0.04 —— **跟著圓的頂棚走，不是平板**，所以走盒切：
 * 無線電艙頂窗（±0.42、機體 z 2.43…2.83）與它後面的**開放槍位**
 * （±0.45、3.23…4.40）。後者就是 `RADIO_HATCH` 那個「中線凹陷」的來源，
 * 兩邊指的是同一個洞。
 *
 * **尾艙罩的玻璃是一條水平的帶，由左側繞過屁股到右側；頂與底都是蒙皮。**
 * 判準不能用「離頂的角度」—— 那只切得出左右兩片，切不出繞過後端的環。改用
 * **面心的高度**：機體 z ≥ 14.95、1.45 ≤ z ≤ 1.88；後端封蓋的面心在 1.65，
 * 自然落在帶內，環就接起來了。透明件在這一段拆成三片，高度範圍都在那條帶上：
 *
 * ```
 *   側窗（前）  機體 z 14.83…15.13   高度 1.55…1.88
 *   側窗（後）  機體 z 15.20…15.73   高度 1.40…1.91
 *   後窗        機體 z 15.79…16.07   高度 1.39…1.92   x ±0.348
 * ```
 *
 * 後窗量到 x ±0.348、一路到機體 z 16.07 —— 罩子的尾端因此要**鈍**，收成尖的
 * 就沒有那面窗可言；但**鈍不等於切平**。整個剖面平切一刀，玻璃帶會被一片豎直的
 * 平板封住，由上往下看是「兩條側窗 + 一道橫牆」；參考模型是**由左繞過屁股到右
 * 的 U 形收口**。逐站極座標量到的最大半寬與中線頂高：
 *
 * ```
 *   機體 z   15.70   15.85   15.95   16.00   16.05
 *   半寬      0.354   0.343   0.270   0.222   收完
 *   頂高      1.967   1.970   1.972   1.742   1.506
 * ```
 *
 * 半寬 15.85 之後三站掉光、頂高最後兩站才塌 —— 尾端是**先收窄再壓低**的圓穹。
 * 末端那一環的封蓋面心落在高度帶外（1.36），靠「機體 z ≥ 16.0 一律算玻璃」把
 * U 的底部接起來。頂部是蒙皮這件事要把透明件與不透明件**分開打**才判得準
 * （只比「哪一件比較外面」會翻）：x 0.20 的頂面全段沒有任何透明交點，只有中線
 * 那條 |x| ≤ 0.15 的細縫有，那是尾砲的槍口開孔，這個解析度做不出來。
 *
 * `B17_Hood` 是**一件 loft、逐面依高度塗材質**，不做布林 —— 罩子本來就是自己的
 * 實體，沒有開口可言，只是同一塊蒙皮上哪一段是玻璃。
 *
 * 機身側面往後還有四處，同樣是平面：
 *
 * ```
 *   無線電艙側窗 ×2  0.83…1.03   2.81…3.15   1.05…1.32   殘差 0.006
 *   腰窗（右）       0.85…1.16   5.88…6.65   0.61…1.33   殘差 0.028
 *   腰窗（左）       0.82…1.12   7.36…8.32   0.64…1.31   殘差 0.024
 *   後小窗（只有右） 0.98…1.02   9.37…9.68   0.60…0.90   殘差 0.004
 * ```
 *
 * **機首兩側的砲位也是錯開的，而且一側凸一側平。** 剖面一律由右側量，機體
 * z −4.04…−4.82 那一段右側是**凸出來的砲位泡罩**，半寬被抬 6…9 cm；鏡射到左邊
 * 就多出一條又長又淺的稜線。高度 0.80 的逐點對照：
 *
 * ```
 *   機體 z   −3.9    −4.2    −4.5    −4.8
 *   右       1.008   0.997   1.014   0.838
 *   左       1.010   0.963   0.906   0.835
 * ```
 *
 * 右側從 −4.0 起不再收、−4.5 反而長回去、−4.8 一刀掉下來；左側是一條直線。
 * **左側才是蒙皮**，那一段改量左側（`BLISTER_SWAP`）。不能用「整條高度帶作廢
 * 再內插」—— 那一帶是剖面的整個中腰，拉直線之後 −4.4／高度 0.70 會由 0.967 掉到
 * 0.914，比泡罩的誤差還大。錯開的好處就是另一側一定乾淨，直接換邊量。
 *
 * 平的那兩片窗補進 `GLASS_PANES`：左舷 −4.11…−4.54、右舷 −4.96…−5.40，PCA 殘差
 * 都是 0.004。對面同一段的泡罩殘差 0.025／0.033，不是平面，沒有做。
 *
 * **腰窗左右錯開將近 1.5 m** —— B-17G 後期型本來就這樣，兩個腰部射手不會撞在
 * 一起；右後那一片也只有單邊。這幾片的角點落在自家蒙皮外 0.003…0.025，正好就是
 * PANE_OUT，不必另外對位。它們後面要有 `B17_Inner`（機身環縮 0.88 的殼）擋著，
 * 否則從一側直接看穿到另一側的天空（坑 24）。
 *
 * **風擋的中線邊比外緣往前 0.42**，那個往前戳的 V 是 B-17 的特徵。
 *
 * 除了頂窗（趴在圓頂棚上，走盒切）與機首罩之外，其餘都做成平面四邊形：四角
 * 投影到最佳平面壓平 → 沿法線外推 2.5 cm → 朝外那一面是玻璃、其餘是機身色的框。
 *
 * **切刀是由機身軸心射出的角錐，不是沿法線平推的柱體。** 平推的話開口邊界是
 * 「玻璃輪廓沿法線的投影」，而法線與蒙皮常常是斜的 —— 風擋的法線與機身側面
 * 夾角 58°，往內擠 0.45 就把開口在斜切方向拖長 0.45 × tan58° ≈ 0.7 m，
 * 蒙皮的切邊掉到 z 1.35 而玻璃下緣在 1.458，外下角裂開 10 cm。角錐的頂點放在
 * 同一站的機身軸心，開口變成「玻璃輪廓由軸心的中心投影」，投影誤差不到 5 mm。
 *
 * 驗收（每片 11×11 格點 + 輪廓外 3%／6%／10% 三圈）：四片玻璃**沒有一點被蒙皮
 * 蓋住，也沒有一處外緣漏光**。
 *
 * **機首罩的框是同心圓**：投彈手機首罩整顆都是玻璃 —— 由 (0, y, 0.45) 打 72 個
 * 方向，機體 z −5.60…−6.32 每一站都是 72/72 命中，半徑 0.794 一路收到 0.034。
 * 剖面既然是完整的一圈，隔框就是完整的一圈：等 y 的剖面線由正前方看就是圓，
 * 三道（半徑約 0.78／0.53／0.28）併排就是同心圓，再加 45° 一條、共八條的輻射條
 * （`meridian`：同一個方位角沿機首方向掃，條帶的寬度方向取該方位的**切線**，
 * 不然斜著擺的那幾條會變窄），由正前方看就是投彈手那一格一格的罩子。
 *
 * **框的法線要拿射線打到的蒙皮法線逐面校正** —— 面的繞向跟著掃描方向走，整圈
 * 掃反了就整條朝內，算圖上被背面剔除、整條看不見，`geometry.test.ts` 的
 * 「每一個網格都是法線朝外」也會紅。
 * 射線落空的角度要在條帶上斷開，否則缺口兩端會被一個四邊形接起來，變成一片飛
 * 在外面的白楔子。
 *
 * ── 翼根：主翼穿過機身那一段沒有獨立的機身蒙皮 ──────────────
 *
 * 由外往內的射線讀到主翼、由內往外讀到彈艙內壁，兩者都通得過上下限檢查
 * （1.15 對真值 1.16 只差 1 cm，0.041 剛好卡在下限），所以 `ok` 是 True、
 * `fill_bands` 不會補 —— 症狀是下半身的級線在機體 z −0.6…1.6 整組亂掉。
 * 做法是把主翼厚度帶（高度 −0.80…0.70、機體 z −1.75…4.75）內的取樣直接判為
 * 量不到，交給 `fill_bands` 沿 **y** 補；翼根前後兩站的同一級只差 1…4 cm，
 * 機身在那一段本來就幾乎等剖面。
 *
 * ── 機身拆成子彈本體 + 機背整流 ──────────────────────────────
 *
 * `B17_Fuselage` 的環頂端是**折線上的兩點**，`B17_Dorsal` 從那圈邊往上長到
 * 冠線；兩件共用那圈邊，合起來的外皮與單件 loft 相同。這台的機背是
 * 「圓剖面 + 抬高的甲板」：機體 z 0.0 最寬 1.172 落在高度 0.50（圓頂在 1.67），
 * 而冠線量到 2.00 —— 高出的 0.33 就是座艙頂到無線電艙的甲板。甲板高度到機體
 * z 4.8 之後量到的是 **−0.01**（剖面就是一個圓、冠線正好是圓頂），所以機背件
 * 收在 z 4.4，再往後那一段屬於機身，接手的是 `B17_Fin` 的背鰭整流罩。
 *
 * **折線放在量到的「剖面圓頂」（最大半寬那一點的高度 + 半寬），不是曲率膝點。**
 * 膝點量到的是艙緣，由風擋的 1.518 一路掉到 1.296，比真正的甲板底低 0.26；
 * 而級數是腹線到折線的固定比例，八條腰線因此整組下沉（第 6 級由 1.207 降到
 * 1.057 再回升，中間凹 15 cm）。改放圓頂之後折線是 1.518 → 1.688 單調上升，
 * 腰線跟著全段單調。**也因此不能像 F4F 那樣壓單調** —— 那台的折線是水滴線只能降，
 * 這台的圓心隨腹線一路上抬。算圓頂時要跳過剖面首尾兩個極點：`station()` 把它們
 * 強制標成有效，不跳的話主翼段那個「量不到、沿 y 補」的判斷會失效，圓頂虛高 0.25。
 *
 * **剖面是橢圓不是水滴**：最寬處落在腹線→冠線的 **0.500**（機體 z −3.0／4.5／
 * 7.0／10.0／13.0 五站都是），與四台戰鬥機相反，別照戰鬥機的直覺推。
 *
 * ── 量測陷阱：天線 ──────────────────────────────────────────
 *
 * 參考模型的 `Object_36`（32 個三角形）是從垂尾頂拉到機首的鋼索片。由上往下
 * 打中線射線會把它讀成背鰭整流罩，讀出來是**斜率剛好 0.4167 的完美直線**
 * （機體 z 6.6→12.2 的高度 2.474→4.745），平滑、單調、逐站連續，比真值高
 * 0.5…1.5 m。分辨方法是多打幾發看它底下有沒有東西：機體 z 9.0、x 0.05 由上
 * 往下的交點是 3.475（片頂）、2.245（片底）、1.618（機身冠線），中間 0.63 m
 * 是空氣 —— 結構整流罩不可能懸空。第一代量這台時踩過同一個坑，代價是整片垂尾。
 */
