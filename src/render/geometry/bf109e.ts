import { Vector3 } from 'three'
import { DEG } from '../../core/math'
import { createHull, type AircraftModel, type Blister, type FinParams } from './assembly'
import { BF109E_HULL } from './bf109e.hull'
import type { CanopyStation } from './canopy'
import { prepareRings } from './hull'
import type { WingParams } from './wing'

/**
 * Bf 109 E-4 的程序化外型 —— 真機全長 8.64 m、翼展 9.87 m、
 * 螺旋槳直徑 3.10 m。
 *
 * 【為什麼外型是 E，而飛行模型不是】專案負責人提供的參考模型是 E-4，
 * 並指定**外型**維持 E。飛行模型與武裝則另有裁決：
 *
 *   2026-08 之前   E-4 外型 + G-6 性能（DB 605A、MG 151/20）
 *   2026-08-25 起  E-4 外型 + **K-4** 性能（DB 605DC、MK 108），
 *                  負責人明示「3D 模型不要動」「E-4 外型 + K-4 性能 沒錯」
 *
 * 也就是說這個檔案**刻意不跟著性能走**。要改外型是另一個決定，要先問過。
 * 詳見 specs/bf109k4.ts 檔頭。
 *
 * E 與 G／K 在外觀上的關鍵差異，四項都已對應（也就是四項都**沒有**做）：
 *
 *   方翼尖    F 型才改成圓翼尖，E 是方的（因此沒有 tipRound）
 *   尾翼支柱  F 型起改懸臂式取消支柱，E 有；K-4 另有加高的木製垂尾
 *   無 Beulen 13 mm MG 131 的鼓包是 G-6 起的特徵（K-4 的更大）；E 的 MG 17
 *             是埋進引擎罩的，外面只有凹槽，沒有任何凸出物
 *   機首較短  8.64 對 8.95 m。K-4 另有可收放尾輪與 Erla Haube 座艙罩
 *
 * 【座標是機體座標，不是造型座標】機身外殼的環直接量自參考模型，量到的
 * 就是對齊後的機體座標，所以這一台的 offsetZ 是 0，其餘零件也一律用機體
 * 座標寫（機首約 −2.48、機尾約 6.17）。P-51D 仍是造型座標 + 位移。
 */

/**
 * 座艙 —— 側視四段輪廓量自參考模型的正交剪影：
 *
 *     後 \‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾\ 前     ← 機首在右
 *         \______________|
 *
 *   風擋   自 z = 0.355 的機背高度斜升到 0.525 的 0.965
 *   罩頂   0.965 → 0.925，1.04 m 只降 0.040，側面看就是水平
 *   艙緣   固定 0.520
 *   尾斜切 艙緣自 z = 1.395 抬到 1.595 的 0.720（正好 45°），再往後高過
 *          罩頂，輪廓自己收成一點
 *
 * 正視是梯形（窄平頂 0.21 + 平側玻璃），參考模型實測如此，不是圓拱。
 *
 * 【艙緣是唯一量不出來的一條線】參考模型在座艙段的最外側就是玻璃本身，
 * 機身開口的邊緣被擋住了。0.520 是人工定的，其餘全部照量測值。
 */
const CANOPY: readonly CanopyStation[] = [
  { z: 0.255, sill: 0.520, roof: 0.829 },   // 風擋底框，齊機背
  { z: 0.425, sill: 0.520, roof: 0.965 },   // 風擋頂
  { z: 0.875, sill: 0.520, roof: 0.945 },
  { z: 1.295, sill: 0.520, roof: 0.925 },   // 滑動罩尾端，尾斜切自此起
  { z: 1.495, sill: 0.720, roof: 0.915 },
  { z: 1.695, sill: 0.910, roof: 0.907 },   // 艙緣高過罩頂 → 收成一點
]
const CANOPY_SHAPE = { topWidth: 0.21 }

/**
 * 座艙段補上加密的環。
 *
 * 【為什麼機首與玻璃罩的接合處會凹陷】開口的前壁是「最後一個完整的環」到
 * 「第一個被切開的環」之間那一段。原本前面最近的環在 z = 0.060，開口從
 * 0.355 起——機背因此從 0.823 一路斜降到艙緣 0.520，斜面長達 0.295 m，
 * 側面看就是機首後方塌下去一塊。補一個 z = 0.345 的環之後，前壁只剩
 * 0.010 m，等於一道垂直的隔板。尾端同理補 1.805。
 *
 * 順帶把座艙段整體加密：那裡是全機最常被盯著看的地方，18 圈不是硬性上限。
 */
const CANOPY_EXTRA_Z = [0.245, 0.340, 0.600, 1.080, 1.400, 1.600, 1.705]

const RINGS = prepareRings(BF109E_HULL, [...CANOPY.map((s) => s.z), ...CANOPY_EXTRA_Z])

/**
 * 主翼。
 *
 * 【機身整體往前移了 0.10 m，不是機翼往後】對參考模型 x = 1.5…4.7 的前緣
 * 配一條直線（每站 0.006 m，線性到不能再線性）再外推到 x = 0，落在 −0.4545；
 * 本模型的翼根前緣是 −0.555，**機翼相對機身往前 0.10 m**。四分之一弦線必須
 * 壓在原點（重心），所以機翼不能動——移的是機身、座艙、尾翼、螺旋槳與所有
 * 貼在機身上的凸起，全部 −0.10。翼下散熱器貼在機翼上，不跟著動。
 *
 * 修完前緣逐站差 1 mm。旁證：風擋底框原本落在翼弦的 41%，移完是 36.5%
 * ——與 P-51D 量到的 36.5% 完全一致，兩台真機的風擋都在這個位置。
 *
 * 【弦長與厚度不採用量測值】參考模型的機翼比真機大：量到翼根弦 2.279、
 * 厚弦比 16.9%，而 spec 對得上的是 2.22（MAC 1.691 對 spec 1.68、翼面積
 * 15.94 對 16.05）與真機 NACA 2R1 的 14.2%。同一台參考模型的尾翼卻小了
 * 11%（見 TAILPLANE），**它的比例本來就不準**，只有位置可信。
 *
 * 【上反角同理維持 6.5°】參考模型量到 5.26°（1.5→3.0 三段斜率 0.094／
 * 0.092／0.090，量得很乾淨），但真機是 6°30'。rootY 由 −0.37 抬到 −0.34
 * 讓中厚線在乾淨站位（x 2.2–3.0，避開內側散熱器與外側前緣縫翼）對到
 * ±0.013；兩端因上反角差異各留約 0.05。
 */
const WING: WingParams = {
  // E 型是**方翼尖**（F 型才改圓），所以沒有 tipRound。
  // 真機 NACA 2R1：翼根 14.2% × 2.22 = 0.315、翼尖 11.35% × 1.01 = 0.115。
  rootChord: 2.22, tipChord: 1.01, halfSpan: 4.935,
  // 後掠 3.45° 量自參考模型（x 1.5→4.7 前緣後移 0.193 m）
  sweep: 3.45 * DEG, dihedral: 6.5 * DEG, thickness: 0.315, tipThickness: 0.115,
  rootZ: -0.555, rootY: -0.34,
}

/**
 * 水平尾翼 —— **維持史實值，不採用參考模型的量測值**。
 *
 * 參考模型量到半翼展只到 x ≈ 1.47（真機翼展 3.30 m ÷ 2 = 1.65，小了 11%），
 * 垂尾頂端量到 1.09 而本模型是 1.45。同一台模型的主翼卻大 2%——尾翼整組
 * 被縮小了，位置與尺寸都不可信，所以這一組跟著機身一起 −0.10 就好，
 * 不去追它。這是「參考模型只當量尺，量尺自己也要驗」的實例。
 */
const TAILPLANE: WingParams = {
  rootChord: 1.06, tipChord: 0.56, halfSpan: 1.65,
  sweep: 10 * DEG, dihedral: 0, thickness: 0.12, tipThickness: 0.055,
  rootZ: 4.905, rootY: 0.55, tipRound: 0.35,
}

const FIN: FinParams = {
  chordRoot: 1.50, chordTip: 0.68, height: 1.05, sweep: 30 * DEG, z: 4.525, rootY: 0.40,
}

/**
 * DB 601 的排氣管：**每側 6 根**（倒立 V12，每側 6 缸），沿引擎罩下側排成
 * 一列。用產生器而不是手打六筆，是因為間距與尺寸要一致才會讀成鋸齒狀；
 * 手打很容易在某一根上打錯一個位數而不自覺。
 */
function exhaustStubs(startZ: number, pitch: number, count: number): Blister[] {
  return Array.from({ length: count }, (_, i) => ({
    x: 0.44, y: 0.15, z: startZ + i * pitch,
    width: 0.10, height: 0.12, length: 0.14,
    mirror: true,
  }))
}

const BLISTERS: readonly Blister[] = [
  /**
   * 增壓器進氣口 —— **只在左舷（−X）**，不鏡像。
   *
   * DB 601 的機械增壓器裝在引擎左側，進氣口因此是單邊的；這是 109 少數
   * 左右不對稱的外觀特徵，從正面或俯視一眼可辨。
   */
  { x: -0.46, y: 0.35, z: -0.545, width: 0.22, height: 0.28, length: 0.58, round: true },

  ...exhaustStubs(-1.175, 0.193, 6),

  // 機首下方滑油冷卻器
  { x: 0, y: -0.30, z: -0.695, width: 0.40, height: 0.20, length: 0.87 },
  /**
   * 翼下冷卻液散熱器 —— 位置與傾角都由**機翼自己的幾何**算出來，不是配的。
   *
   * 【為什麼要傾斜】機翼有 6.5° 上反角，厚度又沿翼展收，所以下表面在散熱器
   * 內外兩端的高度差了 0.074 m（內端 −0.363、外端 −0.289）——實測 7.7°。
   * 原本的方盒是水平的，內側陷進機翼、外側浮空，側面看得出一道楔形縫。
   *
   * 【長度與高度】機翼現在是翼型剖面，下表面只有在三成弦長處最低、往後
   * 逐漸抬起。方盒的頂面是平的，蓋不住這段起伏——原本 0.95 長的盒子在
   * 後端會離開機翼 0.06 m，露出一條縫。縮到 0.65（涵蓋 28%～63% 弦長，
   * 起伏只剩 0.038）並把上緣抬到 −0.25，四個角就全部埋進機翼裡：
   * 外端後角埋 0.003、內端前角埋 0.077。
   */
  {
    x: 1.50, y: -0.33, z: 0.375, width: 0.55, height: 0.22, length: 0.65,
    rotZ: 7.7 * DEG, mirror: true,
  },
  /**
   * 水平尾翼斜撐桿 —— **E 型有**（F 型起改懸臂式取消）。自機身下緣
   * 拉到平尾下表面，長 0.722、仰角 42.8°。
   */
  {
    x: 0.355, y: 0.245, z: 5.125, width: 0.722, height: 0.05, length: 0.10,
    rotZ: 42.8 * DEG, mirror: true, bodyColor: true,
  },
]

/** 機身色。零件（`render/debris.ts`）要用同一個值 —— 見 `P51D_BODY_COLOR`。 */
export const BF109_BODY_COLOR = 0x7e8a73

export function buildBf109E(): AircraftModel {
  const h = createHull({
    bodyColor: BF109_BODY_COLOR,
    accentColor: 0x33403a,
    realLength: 8.64,
    offsetZ: 0,
    // 眼點：艙緣 0.520 上方 0.26，罩頂在 z 0.60 約 0.955、頭部餘裕僅 0.175
    // ——109 的座艙本來就以窄小出名；z 0.60 落在風擋（0.255…0.425）後方 0.18 m
    eyePoint: new Vector3(0, 0.78, 0.60),
    // 右翼尖弦的中點，由 WING 推出（`buildWingPanel` 的 u = 1 站位）：
    //   x = halfSpan                          = 4.935
    //   y = rootY + tan(dihedral) × halfSpan  = −0.34 + tan(6.5°)×4.935 =  0.2223
    //   翼尖弦 = tipChord（**方翼尖，沒有 tipRound**）                   =  1.0100
    //   前緣  = rootZ + tan(sweep) × halfSpan                           = −0.2575
    //   z    = 前緣 + 弦/2                                               =  0.2475
    // 與 P-51D 的差別一眼可見：上反角大 1.5°、翼尖弦是它的兩倍多（方翼尖），
    // 半翼展小 0.7 m —— 共用一條推導規則不可能對兩台都準。
    wingTip: new Vector3(4.935, 0.2223, 0.2475),
  })

  h.cockpit(RINGS, CANOPY, CANOPY_SHAPE)

  h.wingPair(WING)
  h.wingPair(TAILPLANE)

  h.upright(FIN, 0.12, 0.35)   // 垂尾頂端是圓的

  h.blisters(BLISTERS)
  h.propeller({
    // 底徑實測 0.0827 L；y 與機首環中心一致
    spinnerRadius: 0.35, spinnerLength: 0.34, spinnerY: 0.36,
    blades: 3, propZ: -2.355, propRadius: 1.55,   // 真機 VDM 螺旋槳直徑 3.10 m
  }, RINGS[0]!.z)

  return h.finish()
}
