import { Vector3 } from 'three'
import type { GlbAircraft } from './glb'

/**
 * F4F-4 Wildcat 的外型 —— 在 Blender 裡對著參考模型直接量、直接 loft。
 *
 * 幾何全部在 Blender 裡建（來源 `tools/blender/f4f4.blend`；建模腳本
 * `tools/blender/build_f4f4.py` 是它的出處），直接匯出 `public/models/f4f4.glb`，
 * 4,602 個三角形（F6F-5 是 2,992、Ki-84 是 4,180 級）。
 *
 * 【機身與機背是兩件】`F4F_Fuselage` 是子彈狀的機身本體，`F4F_Dorsal` 是**風擋
 * （y −0.02）到垂尾根**的機背整流，兩件共用「折線」那一圈邊 —— **外皮與單件 loft
 * 幾乎完全相同**（側視上緣 17 個站位裡 14 站逐點 0.000，只有風擋根那 3 站差 5…6 mm，
 * 那是機背收尾的過渡）。拆的理由在 `build_f4f4.py` 的 DORSAL_Y 註解：單件時 8 個
 * 級數要從腹線一路撐到冠線，餘弦分佈又把點擠在上下兩端，曲率最大的肩部只分到三級、
 * 間距 0.30 m，算圖上是兩片平板夾一道硬稜。
 *
 * 【折線是構造線，不是外皮】它只決定兩件在哪交班與各自的級數怎麼分；只要落在腹線
 * 與冠線之間，合起來的外皮一個頂點都不會動。所以它不照逐站量到的曲率膝點走 ——
 * 那個膝點在座艙段量到的是**艙緣**，機身自己的線會兩站之內掉 0.10，而級數是腹線到
 * 頂線的固定比例，八條級線在那裡整組俯衝。現在它是一條由機首拉到機尾、44 站一次
 * 都不回頭的水滴線（峰在風擋 0.813，尾錐 0.068），機背厚度則照 `f4f_wildcat.glb`
 * 的比例（y −2.5 是 0.33，膝點版本是 0.43）。細節見 `build_f4f4.py` 的
 * H_DORSAL 與 BLEND_END_Y。
 *
 * **風擋之前沒有機背整流**，那一段是機身甲板。座艙玻璃
 * 是從 `F4F_Dorsal` INTERSECT 出來的 —— 艙緣線（前 0.808、後 0.698）在整個座艙段
 * 都高於折線，罩子的外皮整片屬於機背，從機身切會得到空網格。
 *
 * 【GLB 的座標系就是機體座標】實測包圍盒：
 *
 *     X −5.790 … 5.790   Y −0.816 … 1.790   Z −2.380 … 6.142
 *
 * X 對稱於 0（翼展 11.58 m，真機 11.58）、Z 的原點落在**機翼四分之一弦線**，
 * 與另外六台的約定相同。
 *
 * ── 參考模型與它的驗收 ──────────────────────────────────────
 *
 * `ref/grumman_f4f_wildcat.glb`（163k 三角形；`ref/f4f.glb` 是 3,140 面的
 * lowpoly，只當第二把量尺交叉驗證）。**這是本專案到目前為止比例最準的一支
 * 參考模型** —— 四個獨立的量各自對上真機，一個都不必校準：
 *
 * ```
 *                     量測值    真機      差
 *   翼展              11.520   11.58    −0.5%（縮放 ×1.00519 之後為 0）
 *   全長               8.753    8.76    −0.1%
 *   螺旋槳直徑          2.98     2.97    +0.3%
 *   主輪輪距            2.13     2.08    +2.4%
 *   翼面積（積分）      24.1     24.15   −0.2%
 * ```
 *
 * 【姿態不必轉】三片槳葉（一片朝上、兩片朝下）的**縱向範圍完全相同**
 * （Y 3.89…4.04），槳盤沒有傾斜 → 推力線水平、pitch = 0。這比用剪影目測
 * 可靠得多（P-51D 那次憑側視估成 −9.5°、實際是 −14.0°）。
 *
 * ── 這一台在量測上與前幾台不同的四件事 ─────────────────────
 *
 * **（一）中翼。** A6M5／Ki-84 是低翼，翼根整流罩只擋腹線；F4F 的主翼接在
 * 機身半高，翼根那一段（z −0.10…+0.25）機身側面整條被擋住，而且參考模型在
 * 那裡**根本沒有機身蒙皮** —— 從機身內往外打的射線會直接穿出去。
 * 這正是「F4F 不能拿 F6F 縮小來改」最硬的證據：翼根弦線坐在機身深度的六成半
 * （機身在該站跨 y −1.04…+0.70），而 F6F 的 `WING.root_y = -0.383` 是壓在
 * 下緣的低翼。
 *
 * **（二）主輪艙與中線龍骨。** 參考模型的起落架是放下的、輪艙是開的洞：
 * 向下的射線在 y 0.15…0.75 打進艙裡讀到艙頂（−0.08…−0.28，真值 −0.75），
 * 而由外往內的水平射線一路穿到中線上一片 |x| = 0.02 的隔板 —— 一個**通得過
 * 上限檢查**的假值，害得下半身被夾成一條縫。這個專案不做輪胎凹槽，所以
 * 整個翼根段的腹線用兩端實測值拉直。
 *
 * **（三）天線索。** 機背到垂尾頂有一條 24 頂點的索。不刪的話「垂尾側視
 * 上緣」量出來是 1.80 而不是真值 1.66 —— 一條平滑、單調、看起來完全正常的
 * 線（技能坑 37 原封不動再演一次）。清理是靠**拆連通塊**：這支模型照材質
 * 合併，41 塊裡只有主體與水平尾翼的翼展幅度 > 3 m，其餘 39 塊全是雜件。
 *
 * **（四）方向舵的鉸鏈是一道凹槽，一條射線會掉進去。** 參考模型在
 * y = −5.50 有一條抹縫，向內的射線在那裡讀回 0.029 —— **一個與高度無關的
 * 定值**（z 1.44/1.48/1.52/1.60 全是 0.0290±0.0001，而兩側 20 mm 外是 0.0500
 * 與 0.0435）。蒙皮沿高度是漸縮的，讀到定值就代表打到的是鉸鏈整流的內壁。
 * 0.40 弦長處在 z 1.48…1.56 正好掃過這條線，垂尾的厚度分佈於是由 .0502 塌到
 * .0199 再彈回 .0460，平面著色下是一塊突出的矩形。
 * `build_f4f4.py` 的 `skin_hw()` 用一窗射線＋穩健線性擬合把它擋掉，**只在偵測
 * 到時才介入**：11 站 × 5 欄共 55 個值裡只動一個。細節與兩條走不通的路
 * （中位數濾波會把近前緣那一欄往外撐 9…22%；事後拉普拉斯的門檻蓋不住 20 mm）
 * 寫在該函式的註解裡。
 *
 * ── 尾段的三個「站位少量一段就整個填平」的特徵 ─────────────
 *
 * 三個的成因相同：**只量外側、內側靠線性外推（或用一條為了濾掉別的東西而
 * 設的門檻），於是真正的形狀被填掉。**
 *
 * **升降舵讓方向舵的缺口。** 水平尾翼的後緣在 x < 0.75 是不後掠的
 * （−6.115／−6.109／−6.109），但 x < 0.35 有一條直線的缺口：
 *
 * ```
 *   x      0.15    0.20    0.25    0.30    0.35    0.40 以外
 *   後緣  -5.666  -5.788  -5.910  -6.031  -6.120  -6.109（平）
 * ```
 *
 * 每 0.05 往後 0.122，外推到中線是 −5.30。只量 0.40 以外的話翼根弦會做成
 * 1.63（真值 1.50）而且缺口整片被填平 —— 根部看起來像多了一塊整流罩。
 *
 * **方向舵的下緣。** 也是一條直線（每 0.05 往後升 0.040），而且**機身尾錐在
 * y −5.92 就結束了**（−5.90 還有最低面 −0.040，−5.95 只剩中線上一片 0.159 的
 * 薄邊，那已經是方向舵）。把垂尾根站平伸到 −6.13 會生出一片從尾錐伸出去的
 * 薄板。那條線在 z 0.30 給 −6.127，而該站**實測**的後緣也是 −6.127 —— 合成站
 * 與量測站自己對上了，接縫是零。
 *
 * **背鰭（dorsal fin）。** F4F-4 的機背有一條窄脊一路長進垂尾。中線比離軸
 * 0.12 處高 0.06…0.16，而它在 y −4.0 的半寬只有 0.10 —— 用來濾掉垂尾薄板的
 * 「寬度 ≥ 0.13」門檻會把整條背鰭一起砍掉，中線頂線因此低 0.04…0.16。
 *
 * 治法**不是**把門檻往後推。參考模型在那一段的剖面是「機身 + 一片等寬的
 * 背鰭」，中間有一道折：
 *
 * ```
 *   y = -4.4   z 0.20   0.25   0.30   0.35   0.40   0.45   0.50
 *   參考半寬   0.257  0.186  0.125  0.116  0.115  0.108  0.100
 *                            ↑ 折，之後是等寬 0.115 的鰭
 * ```
 *
 * 折以下是機身、折以上是背鰭。門檻推到 −4.55 的話機身自己會長出一根尖刺去
 * 重複垂尾那片板，剖面不再是水滴狀的內收，看起來像頂點被抬高。門檻留在
 * 觸底的 −4.02，機身在 y −4.4 的剖面就與參考逐點差 ≤ 0.01。
 *
 * 真正治好台階的是**垂尾低處的前緣改成反解中線頂線**，不是線性外推：背鰭
 * 往前掃的斜率是 −2.92/單位 z，而 0.80／1.05 兩站只有 −0.90，用後者外推會
 * 讓 y −4.0…−4.4 整段缺一塊（實測差 0.12…0.27）。而且那一段的前緣是**凸**
 * 的，z 站位太疏會被 loft 用直線切掉 0.05，所以 0.80 以下補到六站。
 *
 * ── 驗收 ────────────────────────────────────────────────
 *
 * ```
 *   翼面積（由建好的網格逐站積分）  23.95   對真機 24.15  −0.8%
 *   物件兩兩共面（面心 4 mm、法線平行）  0 對
 *   實心件的帶符號體積  全部為正（框條 −0.048，開放曲面本來就是）
 *   六面實體算圖  沒有看穿、沒有黑貼紙、沒有浮空
 *   固定 y 沿展向掃上表面  主翼與尾翼都單調，沒有曲率變號
 *   中線頂線對切（y −3.4…−5.0）  逐站差 ≤ 0.023
 * ```
 *
 * **【前後緣也要展向平滑，不只是上下表面】** 後緣是刀刃，射線在 z 方向掃時
 * 每一站抓到的極值會跳：水平尾翼在 x 0.40／0.50 讀到 −6.138／−6.138，而參考
 * 模型那一段是平的 −6.115／−6.109 —— 25 mm 的噪聲。鋪在只有 0.10 厚的尾翼上，
 * 固定 y 沿展向看上表面就是「峰─谷─峰」三次曲率變號（技能坑 19），平面著色下
 * 每一條的法線跟著交替。拉普拉斯對**直線是恆等的**，而參考模型的前緣是直線、
 * 後緣是分段直線，所以它只削掉噪聲、不動形狀。主翼的後緣也有同一種噪聲
 * （逐站斜率 0.10…0.18），一起治好。
 *
 * **【誠實揭露：有兩條邊超過 B-17G 那一輪抓出來的 0.67 m】** 機身 1.09 m
 * （座艙挖洞之後留下的內壁）與主翼 0.85 m（翼尖那把扇子）。兩條都不在會被
 * 看到的曲面上，所以沒有平面著色的扇形條紋；要不要照技能坑 56 插一條軸是
 * 負責人的決定。垂尾補了低處三站之後由 1.00 降到 0.57、水平尾翼由 0.645
 * 降到 0.506。
 */
