/**
 * Heinkel He 111 H-6 的程序化外型 —— 真機全長 16.40 m、翼展 22.60 m、
 * 兩具 VDM 三葉槳各 3.50 m。
 *
 * 照片上最能認出它的四件事：
 *   1. **全玻璃的不對稱機首** —— 沒有階梯式風擋，整個機首是玻璃；駕駛座偏左、
 *      機槍座偏右
 *   2. 兩具掛在機翼上的發動機艙，後端拉得很長（主輪收進去）
 *   3. 機腹的吊艙（Bola）—— 機身下方那一塊突出的機槍座
 *   4. 大而圓的垂尾，配上細長的後機身
 *
 * 【全部座標量自參考模型】機身、機翼、尾翼、發動機艙都是同一次三軸切片量出來
 * 的，量測系整體 −2.7465 換成機體座標（見 `he111.hull.ts`）。
 *
 * ── ⚠ 這一版是粗胚 ──────────────────────────────────────
 *
 * 機身外殼已經是量測烘焙的定案品質（曲率變號 3/33 站）。**其餘幾片還沒有
 * 逐站對切驗收過** —— 主翼的上反角與翼根高度、發動機艙的剖面、尾翼的翼根
 * 位置都還是由少數幾個量測值推的。疊圖比對之後會逐項收斂。
 */

/**
 * 全玻璃機首。
 *
 * 【與另外兩台的差別】P-51D 是架在機背上的氣泡罩、Bf 109 是嵌進機身的方框罩，
 * 兩者都是「機身上開一個口，蓋一頂罩子」。He 111 沒有風擋階梯 —— **機首本身
 * 就是玻璃**，從尖端一路包到駕駛艙後方。
 *
 * 所以這裡的「座艙開口」比另外兩台長得多（z −3.05…0.75，共 3.8 m，佔全長
 * 23%），而艙緣（`sill`）是沿著機身最寬處走的，不是一條固定高度的線。
 *
 * 【罩頂取機身背線】玻璃就是蒙皮，所以罩頂線 = 該站位量到的背線。這與另外
 * 兩台不同（它們的罩頂高過機背）。
 *
 * 【艙緣是人工定的】坑 15：參考模型在玻璃段的最外側就是玻璃本身，機身開口的
 * 邊緣被擋住。取該站位背線下方約 0.55～0.75，讓玻璃佔機首側面約六成 ——
 * 照片上 He 111 的機首玻璃分界大致在那個高度。
 */
const CANOPY: readonly CanopyStation[] = [
  { z: -3.05, sill: 0.05, roof: 0.34 },
  { z: -2.65, sill: 0.20, roof: 0.78 },
  { z: -2.25, sill: 0.35, roof: 1.00 },
  { z: -1.85, sill: 0.45, roof: 1.17 },
  { z: -1.45, sill: 0.55, roof: 1.29 },
  { z: -1.05, sill: 0.62, roof: 1.37 },
  { z: -0.65, sill: 0.68, roof: 1.42 },
  { z: -0.25, sill: 0.72, roof: 1.45 },
  { z: 0.15, sill: 0.78, roof: 1.46 },
  { z: 0.55, sill: 0.90, roof: 1.47 },
  { z: 0.75, sill: 1.10, roof: 1.50 },   // 收回機背
]
const CANOPY_SHAPE = { topWidth: 0.35, roundness: 2.4, arcSegments: 4 }

/** 開口前後各補一個相距 0.02 m 的環，前後壁才是垂直隔板而不是長斜坡（坑 10） */
const CANOPY_EXTRA_Z = [-3.07, -2.85, -2.45, -2.05, -1.65, -1.25, -0.85, -0.45, -0.05, 0.35, 0.77]

const RINGS = prepareRings(HE111_HULL, [...CANOPY.map((c) => c.z), ...CANOPY_EXTRA_Z])

/**
 * 主翼。
 *
 * 【量測值（機體座標）】外段 X 3.40…10.20 的前後緣各配一條直線：
 *
 * ```
 *   前緣  −0.641 → +1.055   後掠 14.0°（dz/dx = 0.24941）
 *   後緣  +4.213 → +3.708   前掠  4.3°（dz/dx = −0.07427）
 *   厚弦比 18.2% → 10.9%    真機 NACA 23018 → 23010
 * ```
 *
 * 外推到 X = 0 得**翼根前緣 −1.4884、弦長 5.9535** —— 而 −1.4884 正好是
 * −5.9535/4，也就是四分之一弦線壓在原點。那不是巧合，是 `he111.hull.ts`
 * 的平移量就是這樣定出來的。
 *
 * 【翼尖弦 2.296】= 5.9535 − 0.32368 × 11.30。
 *
 * ── ⚠ 兩個還沒量準的 ──────────────────────────────────
 *
 * **上反角 6°** 是史實值不是量測值。切片量到的「X 外緣隨切面高度外移」給的
 * 是 10.2°，但那個量混了翼型厚度沿翼展的收縮，不是中厚線的斜率。要量準得
 * 逐站取 (vMin+vMax)/2 再配線，下一輪補。
 *
 * **翼根高度 −0.30** 是由機身剖面推的（機翼接在機身腰線略下方），沒有直接量。
 *
 * ── 一個對不上的交叉驗證（坑 16／坑 21）────────────────
 *
 * 這個梯形的面積是 22.60 × (5.9535 + 2.296)/2 = **93.2 m²**，而史實是
 * **86.5 m²** —— 高 7.8%。翼尖圓化只解釋得了 0.8 m²。
 *
 * 依坑 21 的規矩：**有史實值但對不上 → 史實值優先，量測值只拿來定位置。**
 * 所以 `specs/he111.ts` 的 `wing.area` 填 86.5（史實），而這裡的梯形維持
 * 量測值 —— 視覺要的是剪影對得上，氣動要的是面積對得上，兩者在這台參考
 * 模型上剛好差 7.8%，那是模型自己的比例誤差。
 */
const WING: WingParams = {
  rootChord: 5.954, tipChord: 2.296, halfSpan: 11.30, rootZ: -1.4884,
  sweep: 14.0 * DEG, dihedral: 6 * DEG, rootY: -0.30,
  // 厚弦比 18.2% → 10.9%，乘上該站位弦長
  thickness: 1.084, tipThickness: 0.250,
  tipRound: 0.55,
}

/**
 * 水平尾翼。量測值（機體座標，量測系 −2.7465）：
 *
 * ```
 *   X 0.60 → 3.80   前緣 10.303 → 11.383（後掠 18.6°）
 *                   後緣 13.105 → 12.237（前掠 15.2°）
 *                   弦長  2.801 →  0.853   厚弦比 ~10%
 *   半翼展 3.95（`align` 那一趟量到全展 7.889，真機 7.60，+3.8%）
 * ```
 *
 * 外推到 X = 0：前緣 10.100、弦長 3.20。
 *
 * 【rootY 0.0】平尾裝在機身中線附近。沒有直接量到，由該段的機身剖面推的。
 */
const TAILPLANE: WingParams = {
  rootChord: 3.20, tipChord: 0.90, halfSpan: 3.95,
  sweep: 18.6 * DEG, dihedral: 0, thickness: 0.320, tipThickness: 0.090,
  rootZ: 10.10, rootY: 0.0, tipRound: 0.75,
}

/**
 * 垂尾。由「正上方射線」掃出來的側視上緣線讀出（量測系 → 機體）：
 *
 * ```
 *   量測 z   13.20  13.50  13.80  14.10  14.40  14.70  15.00  15.30  15.60
 *   機體 z   10.45  10.75  11.05  11.35  11.65  11.95  12.25  12.55  12.85
 *   上緣      0.65   1.58   2.07   2.36   2.54   2.60   2.57   2.33   1.60
 * ```
 *
 * 頂點在機體 z 11.95、高 2.60。前緣由 10.45 升到 11.95 → 後掠
 * atan(1.50/2.60) = 30.0°。
 *
 * 【rootY −0.10 必須低於整段機尾背線】坑 17：取「前緣所在站位的背線」很直覺，
 * 但背線一路降到尾錐的 0.06 —— 垂尾後半會整個懸空，側視看得到底下透出背景。
 * 取 −0.10 讓虛擬翼根低於最後一個機身環，多出來的部分埋進機身反正看不到。
 *
 * 【chordRoot 2.85】由前緣線往下延伸到 y = −0.10 得虛擬翼根前緣 10.39，
 * 後緣取尾錐末端 13.25 → 弦長 2.86。
 *
 * 【tipRound 0.80，不是機翼的 0.55】坑 18：量到的輪廓已含翼尖圓化。真機的
 * 垂尾頂只是小圓角，不是橢圓收尖。
 */
const FIN: FinParams = {
  chordRoot: 2.86, chordTip: 1.30, height: 2.70, sweep: 30.0 * DEG, z: 10.39, rootY: -0.10,
}

/**
 * 發動機艙。**射線原點橫移到 x = 2.6 量的**（`sliceRef` 的 `axisU`，
 * 2026-08-16 為這台加的）—— 從機身軸心射出去會先穿過機身與機翼，取到的
 * 「最外側」是翼尖不是發動機艙。
 *
 * 量測值（量測系 → 機體 −2.7465），四個方向的半徑：
 *
 * ```
 *   機體 z   −2.75  −2.35  −1.95  −1.55  −1.15  −0.75  −0.35  +0.05  +0.45
 *   外側      0.03   0.32   0.50   0.60   0.64   0.63   0.66   0.69   0.70
 *   上緣      0.00   0.32   0.41   0.52   0.52   0.47   0.48   0.45   0.44
 *   下緣      0.00   0.31   0.54   0.58   0.67   0.67   0.96   0.95   0.92
 *
 *   機體 z   +0.85  +1.25  +1.65  +2.05  +2.25
 *   外側      0.65   0.56   0.41   0.24   0.00
 *   下緣      0.96   0.95   0.88   0.77   0.70
 * ```
 *
 * 【下緣從 z = −0.35 起深到 0.96】那是**散熱器與收起的主輪**。真機的
 * He 111 主輪往後收進發動機艙，所以艙的後半特別深 —— 那是它側視最好認的
 * 特徵之一。
 *
 * 【為什麼是 LoftPart 而不是 Blister】`Blister` 是「貼在主體上的一小塊」
 * （進氣口、排氣管），尺度是 0.1～0.5 m。發動機艙長 5 m、直徑 1.3 m，是
 * 主要結構 —— 用盒子做出來會是一根方棍。
 */
const NACELLE: LoftPart = {
  roundness: 2.2,   // 略帶方角的橢圓剖面
  segments: 10,
  sections: [
    { z: -2.75, halfWidth: 0.05, halfHeight: 0.05, centerY: -0.10 },
    { z: -2.35, halfWidth: 0.32, halfHeight: 0.32, centerY: -0.10 },
    { z: -1.95, halfWidth: 0.50, halfHeight: 0.48, centerY: -0.14 },
    { z: -1.55, halfWidth: 0.60, halfHeight: 0.55, centerY: -0.15 },
    { z: -1.15, halfWidth: 0.64, halfHeight: 0.60, centerY: -0.19 },
    { z: -0.75, halfWidth: 0.63, halfHeight: 0.57, centerY: -0.20 },
    { z: -0.35, halfWidth: 0.66, halfHeight: 0.72, centerY: -0.34 },
    { z: 0.05, halfWidth: 0.69, halfHeight: 0.70, centerY: -0.35 },
    { z: 0.45, halfWidth: 0.70, halfHeight: 0.68, centerY: -0.34 },
    { z: 0.85, halfWidth: 0.65, halfHeight: 0.65, centerY: -0.34 },
    { z: 1.25, halfWidth: 0.56, halfHeight: 0.58, centerY: -0.32 },
    { z: 1.65, halfWidth: 0.41, halfHeight: 0.47, centerY: -0.30 },
    { z: 2.05, halfWidth: 0.24, halfHeight: 0.34, centerY: -0.27 },
    { z: 2.25, halfWidth: 0.06, halfHeight: 0.10, centerY: -0.22 },
  ],
}

/** 發動機艙的中心。量測值：`wing` 那一趟的翼厚在 X 2.2～3.2 由 0.9 暴增到 1.54，峰值 2.6 */
const NACELLE_X = 2.6

/**
 * 機身色。
 *
 * 【為什麼是匯出的常數】零件（`render/debris.ts`）要用同一個值 —— 打爆的
 * 飛機掉下來的碎片必須跟機身同色。
 *
 * 【選色】德軍轟炸機的上表面是 RLM 70/71 的墨綠。取偏暗的灰綠，與 109 的
 * 淺灰藍分得開 —— 空戰裡「那是轟炸機還是戰鬥機」要一眼認得出來。
 */
export const HE111_BODY_COLOR = 0x5a6350

export function buildHe111(): AircraftModel {
  const h = createHull({
    bodyColor: HE111_BODY_COLOR,
    accentColor: 0x2b3128,
    realLength: 16.40,
    // 平移已經烘進 he111.hull.ts 的站位裡（量測系 −2.7465）
    offsetZ: 0,
    // 眼點：駕駛座在玻璃機首的後上方、**偏左**（真機的駕駛座偏左，
    // 機首機槍座偏右）。艙緣 0.72 上方 0.30，z −0.25 落在玻璃段中後部
    eyePoint: new Vector3(-0.25, 1.02, -0.25),
    // 右翼尖弦的中點，由 WING 推出：
    //   x = halfSpan                          = 11.300
    //   y = rootY + tan(6°) × 11.30           = −0.30 + 1.1876 = 0.888
    //   翼尖弦 = tipChord × tipFactor(1, 0.55) = 2.296 × 0.55  = 1.263
    //   前緣  = rootZ + tan(14°)×11.30 + (2.296 − 1.263)×TIP_ANCHOR
    //         = −1.4884 + 2.8172 + 0.258      = 1.587
    //   z    = 前緣 + 弦/2                     = 2.219
    wingTip: new Vector3(11.300, 0.888, 2.219),
  })

  h.cockpit(RINGS, CANOPY, CANOPY_SHAPE)

  // 兩具發動機艙。機身色而不是強調色 —— 它們是蒙皮的一部分。
  //
  // 【為什麼是位移 Mesh 而不是給截面一個 centerX】`FuselageSection` 只有
  // `centerY`（單發機的機身與導管都在中線上，橫向偏移從來不需要）。加一個
  // 欄位要動 `buildFuselage` 的內圈迴圈；`loft` 本來就回傳 Mesh，位移它
  // 是同一件事而且不碰共用的產生器。
  for (const sx of [1, -1]) h.loft(NACELLE, h.body).position.x = sx * NACELLE_X

  h.wingPair(WING)
  h.wingPair(TAILPLANE)
  h.upright(FIN, 0.16, 0.80)

  /**
   * 兩具螺旋槳。**`propeller` 現在可以呼叫多次**（2026-08-16 為這台改的）——
   * 原本每次呼叫都會把 `setPropSpin` 整個換掉，雙發時左邊那具永遠不轉。
   *
   * 【`noseZ` 要覆寫】單發機的整流罩接在機身首站上，這台的接在**發動機艙
   * 前緣**（−2.75），與機首（−3.25）差 0.5 m。
   *
   * 【槳盤半徑 1.75】真機每具 VDM 三葉槳直徑 3.50 m。注意 `specs/he111.ts`
   * 的 `prop.diameter` 是 4.95 —— 那是**等效單槳盤**，給動量理論用的，
   * 與這裡的視覺尺寸是兩件事（推導見那一支的檔頭）。
   */
  for (const sx of [1, -1]) {
    h.propeller({
      x: sx * NACELLE_X, noseZ: -2.75,
      spinnerRadius: 0.30, spinnerLength: 0.55, spinnerY: -0.10,
      blades: 3, propZ: -2.30, propRadius: 1.75,
    }, RINGS[0]!.z)
  }

  return h.finish()
}
