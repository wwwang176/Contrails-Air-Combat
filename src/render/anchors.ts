import type { Quaternion, Vector3 } from 'three'

/**
 * # 粒子的錨點
 *
 * 一批粒子**吸附在某個會動的物件上**：位置與速度存的是那個物件的區域座標，
 * 每一幀由它當下的變換組回世界座標。
 *
 * 【為什麼不能用「發射時繼承速度」代替】那只在物件等速直線時成立。掛在
 * 翻滾的殘骸引擎上的火，一離開就被轉動甩開 —— 燒在螺旋槳上的火會飄到機翼
 * 外面，而畫面上那只是「火怪怪的」。
 *
 * 【誰該吸附，誰不該】燒在物件上的火要吸附；它吐出來的煙**不要** ——
 * 煙離開之後就是空氣裡的一團，被拋在後面才會連成尾跡。
 */
export interface Anchors {
  /**
   * 把 `id` 這個錨點當下的世界變換寫進 `outPos` 與 `outQuat`。
   *
   * **錨點已經不在了就回 `false`** —— 掛在它上面的粒子會當場收掉。少了
   * 這一條，殘骸被回收之後它的火會留在最後那個變換上燒完剩下的壽命。
   *
   * 熱路徑：每幀每顆粒子一次，不得配置。
   */
  frame(id: number, outPos: Vector3, outQuat: Quaternion): boolean
}
