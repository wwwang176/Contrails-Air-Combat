/**
 * ホ103（一式十二・七粍固定機関砲）。**機首兩挺，與螺旋槳同調。**
 *
 * 【初速 780、射速 850 都取日方一手】佐山二郎『日本陸軍航空武器』（2021）
 * pp.381, 613：初速 780 m/s、射速 800〜900 発/分、砲重 23.0 kg。美方的
 * TAIC Manual No.1（1944-12）給 2,500 ft/s ≒ 762 與 900 rpm，**兩格都自己
 * 標了 est.**，所以取日方值、射速取區間中點。
 *
 * 【傷害 30 —— 與 MG 131 同一格】
 *
 * ```
 *                彈頭 g   初速 m/s   動能 kJ   傷害
 *   MG 131        34       750        9.6      30
 *   ホ103         36.5     780       11.1      30   ← 這裡
 * ```
 *
 * 彈藥是 12.7 × 81 mm SR（Breda 系），一式徹甲曳光弾彈頭 36.5 g
 *（CINCPAC-CINCPOA Bulletin 85-45, 1945-04, p.66）。**與 MG 131 一樣是打
 * HE 彈的重機槍**（マ103），所以走同一格而不是走 M2 白朗寧那格的 18 ——
 * M2 的彈頭更重（46 g）卻是純動能彈，這正是 MG 131 傷害高於 M2 的理由。
 *
 * 動能比 MG 131 高 16%，所以 30 是保守的一端。**這是起始值，由試飛裁定。**
 *
 * 【同調折減不填】Ki-84 的同調射速沒有任何數據。流傳的「ホ103 同調 400 rpm」
 * 唯一出處是 Rottman, *Browning .50-caliber Machine Guns*（Osprey 2010,
 * p.22），而 en.wikipedia 引完之後**自己用 USSBS 報告反駁**；另一個版本出自
 * Jon Guttman（*Aviation History*, 2017-05），但那句講的是**三葉螺旋槳的
 * 一式戰二型 Ki-43-II**，不是四葉的 Ki-84。本模型也沒有同調折減這個機制。
 */
export const HO103: WeaponSpec = {
  id: 'ho103',
  name: 'ホ103 12.7mm',
  muzzleVelocity: 780,
  roundsPerMinute: 850,
  damage: 30,
}

/**
 * ホ5（二式二十粍固定機関砲）。**翼內兩門，自由射擊、非同調。**
 *
 * 【初速 741 是 HE 彈的值，而且分歧的成因已經查明】
 *
 * *Catalog of Enemy Ordnance*（Office of the Chief of Ordnance, 1945,
 * Japanese p.252）把彈種分開實測：
 *
 * ```
 *   二式曳光徹甲弾 AP-T   123.2 g   2,304 f/s = 702 m/s
 *   二式榴弾 HE            84.3 g   2,430 f/s = 741 m/s   ← 採用
 *   マ206 四式薄肉榴弾     72.4 g              831.9 m/s
 * ```
 *
 * 702–832 這整段跨距**單用彈頭重量就解釋完了**。
 *
 * 【流傳的「後期減裝藥導致初速下降」查無一手來源】它只出現在 AI 生成頁與
 * 論壇轉述鏈上；en.wikipedia 的 Ho-5 條整條掛 `{{No footnotes}}`，其 735 與
 * 750 m/s 兩個數字在同一條目內還自相矛盾。日方史料記錄的問題是**膛炸（腔発）**
 * 與圖面不統一，不是減裝（『歴史群像』2004, p.147）。**不要照那個說法改。**
 *
 * 【射速 850】美方實測給 950 rpm（cyclic，不含供彈損失），日方兩說 750
 *（『陸軍航空技術沿革史』1947, p.106）與 850（『丸メカニック』No.33）。
 * 取 850 —— 日方兩個獨立來源夾住它。
 *
 * 【傷害 80】彈頭 84.3 g @ 741 m/s ＝ 23.1 kJ，與 MG 151/20（92 g @ 705，
 * 22.9 kJ，傷害 84）幾乎相同。取 80 而不是 84：二式榴弾的裝藥是 RDX 3.4 g
 * ＋焼夷剤 3.4 g，比 Minengeschoss 的薄殼大裝藥少。**起始值，由試飛裁定。**
 */
export const HO5: WeaponSpec = {
  id: 'ho5',
  name: 'ホ5 20mm',
  muzzleVelocity: 741,
  roundsPerMinute: 850,
  damage: 80,
}

/**
 * Ki-84-I 甲的四個槍口，**機體座標**。
 *
 * 配置由三份互相獨立的一手文件逐項印證（F-IM-1119C-ND 第 3 頁、TAIC 156A-3
 * 的 ARMAMENT 表、MATSC 手冊 pp.12–14），日方諸元表也對得上：
 *
 * ```
 *   2 × ホ103   機首、駕駛艙前方機身兩側   約 350 発/門   與螺旋槳同調
 *   2 × ホ5     主翼內、起落架收納位外側   約 150 発/門   自由射擊
 * ```
 *
 * ── 機首兩挺：站位由 GLB 的機身縱剖量出來 ────────────────────
 *
 * `test/tools/ki84-hit.measure.ts` 逐 z 印背線與該高度的半寬：
 *
 * ```
 *      z      背線 y   半寬（背線下 0.10）
 *   −2.00     0.629      0.198
 *   −1.80     0.678      0.209
 *   −1.60     0.703      0.212
 * ```
 *
 * 槍口取 z = −1.90（引擎罩中段、罩口 −2.17 之後 0.27）、y = 0.58（背線下約
 * 0.07，埋在罩子的槍槽裡）、x = ±0.18（該高度半寬約 0.20 之內）。做法與
 * `weapons/bf109k4.ts` 的機首兩挺相同 —— 那台取的是背線 0.81 底下的 0.72。
 *
 * ── 翼砲兩門：展向站位由起落架艙外緣定 ──────────────────────
 *
 * 報告寫明它們在**起落架收納位外側**（"in the wings outboard of the
 * landing gear wells"）。真機輪距 131.3 in ＝ 3.335 m，所以輪心在 x ≈ 1.67；
 * 艙門外緣再往外一點。取 **x = ±2.30**。
 *
 * 縱向：前緣是一條直線（`tools/blender/build_ki84.py` 量到 z = −0.621 逐站
 * 不變），槍管往前伸 0.20 m → z = −0.82。弦線高度由量到的兩站外推：
 *
 * ```
 *   x 1.0  弦線 y −0.444        斜率 (−0.061 + 0.444) / 4.0 = 0.0958 /m
 *   x 5.0  弦線 y −0.061        （上反角 5.47°）
 *   x 2.3  → −0.444 + 0.0958 × 1.3 = −0.320
 * ```
 *
 * 【為什麼寫死而不是 import 造型檔】`weapons/` 不該相依 `render/`，與
 * `weapons/p51d.ts`、`weapons/f6f5.ts` 同一條理由。量測腳本是
 * `test/tools/ki84-hit.measure.ts`，`test/unit/hitbox.test.ts` 有一條跨模組
 * 測試守住「每個槍口都落在至少一個命中盒內」。
 *
 * 【機首兩挺不會被併進機翼盒】`hitbox-emit.probe.ts` 只把**展向落在機翼段
 * 範圍內**的掛架併進去，機首那兩挺靠 engine 盒接住。
 */
const MOUNTS: Mount[] = [
  { weapon: HO103, position: new Vector3(0.18, 0.58, -1.90) },
  { weapon: HO103, position: new Vector3(-0.18, 0.58, -1.90) },
  { weapon: HO5, position: new Vector3(2.30, -0.32, -0.82) },
  { weapon: HO5, position: new Vector3(-2.30, -0.32, -0.82) },
]

export const KI84_BATTERY: Battery = {
  /**
   * 【1,000 m，與 P-51D 和 F6F-5 一致】專案負責人在 M10 驗收時對**翼槍**下的
   * 裁決。機首那兩挺在中軸線附近，任何距離都不必修正匯聚 —— 這個史實優勢
   * 從資料自然落出來，與 Bf 109 同理。
   */
  mounts: MOUNTS,
  convergence: 1000,
  /**
   * 預瞄環取**初速最快**的那挺（ホ103，780 對 ホ5 的 741）。寫成從 `mounts`
   * 挑最大值而不是硬指 `HO103`，是為了讓它跟著資料走 —— 日後換槍，基準自動
   * 落在當下最快的那挺。與 `weapons/bf109k4.ts` 同一個做法與同一個取捨：
   * 較慢的那門在中遠距離會落在環的**後方**。
   */
  sight: MOUNTS.reduce((a, b) =>
    (b.weapon.muzzleVelocity > a.weapon.muzzleVelocity ? b : a)).weapon,
}
