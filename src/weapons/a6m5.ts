/**
 * 九九式二〇粍 二号四型固定機銃。**翼內兩門。**
 *
 * 【要澄清一個常見誤解：一号→二号的換裝不是發生在五二型內部】
 * 一号銃（20 × 72RB、初速 600 m/s、彈鼓）是 **A6M2／A6M3** 的裝備；
 * 五二型一開始就是二号銃（20 × 101RB、初速 750 m/s）。五二型系列內部真正的
 * 變化是 **二号三型（彈鼓 100 発）→ 二号四型（彈帶 125 発）**，而那正是
 * 基本型與甲型的差別。本專案沒有彈藥模型，所以那個差別在遊戲裡不存在。
 *
 * 【射速 620】karyu.org 的逐型表（Williams 官網明文推薦）：二号三型 480、
 * 二号四型初期 500、**二号四型量產 620–630**、二号五型 750。⚠️ 二号**五型**
 * 1945 年 5 月才制式，**沒有任何來源說五二型丙裝過它** —— 不要用 750。
 *
 * 【傷害 100】彈頭 128 g @ 750 m/s ＝ 36.0 kJ，是 MG 151/20（92 g @ 705，
 * 22.9 kJ，傷害 84）的 **1.57 倍**。純照動能會得到 132，取 100 ——
 * 九九式的裝藥量比 Minengeschoss 的薄殼大裝藥少得多。
 * **這是全專案單發傷害第二高的槍**（僅次於 MK 108 的 250），而那與零戰
 * 「火力兇但打不了幾秒」的史實印象一致。起始值，由試飛裁定。
 *
 * 【與 G4M 的九九式不共用物件】那台是**一号旋回式**（600 m/s、535 発/分、
 * 45 発彈鼓），彈殼長度都不同（20×72RB 對 20×101RB），是兩款槍。
 * 見 `weapons/g4m.ts`。
 *
 * ⚠️ **兩個要避開的錯誤數字**：Williams 給 Type 99 Mk 1 的初速 525 m/s 是
 * 離群值（TAIC 說 610、karyu 說 600）；en.wikipedia 的 Mk 2「彈頭 44.7 g」
 * 明顯錯誤 —— TAIC 明載 Mk 1 與 Mk 2 用**同一顆彈頭**（126–131.7 g）。
 */
