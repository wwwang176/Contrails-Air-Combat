/**
 * A6M5a 的四個槍口，**機體座標**。
 *
 * ```
 *   2 × 九七式七粍七        機首、引擎罩上方   700 発/門   與螺旋槳同調
 *   2 × 九九式二〇粍二号四型  主翼內           125 発/門   自由射擊
 * ```
 *
 * ── 機首兩挺 ────────────────────────────────────────────────
 *
 * `ID=a6m5 npx vite-node test/tools/japan-hit.measure.ts` 量到引擎罩是一個
 * 獨立的黑殼（`A6M5_Cowl`，z −1.840…−0.780），逐 z 帶的背線：
 *
 * ```
 *   z −1.84…−1.54   |x|max 0.579   背線 0.624
 *   z −1.54…−1.24   |x|max 0.606   背線 0.659
 * ```
 *
 * 槍口取 z = −1.75（罩子前緣 −1.84 之後 0.09）、y = 0.50（背線下約 0.12，
 * 埋在罩內的槍槽裡）、**x = ±0.12** —— 零戰那兩挺是緊挨著中軸線的，
 * 與 Ki-84 的 ±0.18 不同。
 *
 * ── 翼砲兩門 ────────────────────────────────────────────────
 *
 * 真機輪距 3.05 m（輪心 x ≈ 1.53），翼砲在起落架艙外側。取 **x = ±2.05**，
 * 約 37% 半翼展 —— 與照片上砲管整流罩的位置相符。
 *
 * 前緣與弦線由量到的兩站內插：
 *
 * ```
 *   x 2.0   前緣 z −0.574   弦線 y −0.272
 *   x 2.7   前緣 z −0.503   弦線 y −0.204
 *   x 2.05  →     −0.569         −0.267
 * ```
 *
 * 二号四型是長管（20 × 101RB），槍管伸出前緣約 0.25 m → z = −0.82。
 *
 * 【為什麼寫死而不是 import 造型檔】`weapons/` 不該相依 `render/`。
 * `test/unit/hitbox.test.ts` 有一條跨模組測試守住「每個槍口都落在至少一個
 * 命中盒內」。
 */
