import { Vector3 } from 'three'
import type { Battery, Mount } from './types'
import { M2_BROWNING } from './p51d'

/**
 * F6F-5 的六挺 AN/M2 .50 —— **與 P-51D 是同一款槍，所以共用同一個物件。**
 *
 * 【為什麼不另外開一份 WeaponSpec】兩台裝的都是白朗寧 AN/M2 航空型：同樣的
 * 槍管長、同樣的 .50 BMG、同樣的 887 m/s 與 800 rpm。抄一份數字過來的唯一
 * 效果，是哪天有人調 M2 的傷害時**只調到一半** —— 這裡指向同一個物件，
 * 調一次兩台一起動，而且 `weapons.test.ts` 有一條把「指的是同一挺」釘住。
 *
 * 【真機上兩者的差別在彈藥，而本模型沒有彈藥】F6F-5 每挺 400 發、共 2,400；
 * P-51D 是內側兩挺 400、外側四挺 270、共 1,880 發，持續射擊時間差三成。
 * 這是 Hellcat 相對於 Mustang 唯一實質的火力優勢，而它在遊戲裡不存在
 * —— 與 `weapons/bf109k4.ts` 說 MK 108「只有 65 發」是同一個缺口。
 * 要不要補彈藥模型是專案負責人的裁決，不是這裡偷偷用傷害去補。
 */

/**
 * 六挺翼槍的槍口位置，**機體座標**。
 *
 * ── 展向站位 ────────────────────────────────────────────────
 *
 * 【硬的那一半：摺翼線在 x = 2.00，這是量出來的】F6F 的外翼是 Sto-Wing
 * 折疊段，摺線就是上反角的折點。參考模型 `ref/f6f.glb` 量到折點在
 * **x = 2.00 m**（內段上反 1.31°、外段 7.10°，見 Blender 的 `WING`）。
 * 交叉驗算：真機收翼後全寬 16 ft 2 in = 4.93 m，兩個鉸鏈相距 4.00 m，
 * 每側外翼收起來再突出 0.47 m —— 對得上。
 *
 * 三挺槍**一定在摺線外側**（摺翼肋與鉸鏈佔掉內側），所以 x > 2.00。
 *
 * 【軟的那一半：槍位間距 0.38 m 是從 P-51D 借來的】找不到 F6F 的槍位站位
 * 圖（線上只有「三挺、交錯」的文字描述）。借的是**同一款槍的同一種安裝**：
 * P-51D 那三對量到的間距是 0.38 m，那是 AN/M2 加供彈道與彈箱在翼盒裡
 * 一個槍艙的實際寬度，換一台飛機不會變。於是
 *
 *     2.24 = 摺線 2.00 + 0.24（摺翼肋與鉸鏈）
 *     2.62 = 2.24 + 0.38
 *     3.00 = 2.62 + 0.38
 *
 * **這是本檔案最弱的一個數字**，弱在那 0.24 與「間距可以借」這兩個假設上。
 * 它影響的是曳光彈從哪裡冒出來與翼槍的散佈，不影響任何史實驗收值。
 *
 * ── 縱向：真機的三挺是前後交錯的 ────────────────────────────
 *
 * 內側最前、中間次之、外側最後（外側那挺的槍管縮在與前緣齊平的滅焰管裡，
 * 從外面看不到）。前緣線由 GLB 量到是 z = −0.809 + 0.0917·x，槍口再往前
 * 伸 0.25 / 0.12 / 0.00 m：
 *
 *     x 2.24  前緣 −0.604  伸 0.25  →  −0.85
 *     x 2.62  前緣 −0.569  伸 0.12  →  −0.69
 *     x 3.00  前緣 −0.534  伸 0.00  →  −0.53
 *
 * y 取該站位的弦線高度（前緣點就在弦線上）：
 * −0.383 + tan(1.31°)×2.00 + tan(7.10°)×(x − 2.00)。
 *
 * 【為什麼寫死而不是 import 造型檔】`weapons/` 不該相依 `render/`，與
 * `weapons/p51d.ts` 同一條理由。量測腳本是
 * `test/tools/f6f-hit.measure.ts`，`test/unit/hitbox.test.ts` 有一條
 * 跨模組測試守住「每個槍口都在自己的機翼命中盒內」。
 */
const STATIONS: readonly (readonly [number, number, number])[] = [
  [2.24, -0.31, -0.85],
  [2.62, -0.26, -0.69],
  [3.00, -0.21, -0.53],
]

const MOUNTS: Mount[] = []
for (const [x, y, z] of STATIONS) {
  MOUNTS.push({ weapon: M2_BROWNING, position: new Vector3(x, y, z) })
  MOUNTS.push({ weapon: M2_BROWNING, position: new Vector3(-x, y, z) })
}

export const F6F5_BATTERY: Battery = {
  mounts: MOUNTS,
  /**
   * 【跟 P-51D 一樣的 1,000 m，而且這是刻意的】海軍當年的校射距離比這短
   * 得多（F6F 的標準是 250 yd 上下）。這裡不照史實，因為 1,000 m 是專案
   * 負責人在 M10 驗收時對**翼槍**下的裁決（見 `weapons/p51d.ts`）——
   * 兩台同樣是六挺 .50 的翼槍機，匯聚距離不同就等於偷偷改了平衡，而那不是
   * 這一輪要動的東西。要改的話兩台一起改。
   */
  convergence: 1000,
  sight: M2_BROWNING,
}
