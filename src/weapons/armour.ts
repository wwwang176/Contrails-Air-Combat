/**
 * # 口徑免疫
 *
 * **一條規則、一支函數，每一次子彈結算都問它。** 哪裡會咬人由資料決定：
 * 裝甲值 0 代表任何口徑都打得穿，而目前只有艦體填了非零的值（`ShipClass`）。
 * 飛機與甲板上的砲位都是 0，於是它們的傷害與這條規則出現之前逐位元相同。
 *
 * 【為什麼是硬門檻而不是連續衰減】一般會擔心門檻造成懸崖，但這個專案的
 * 口徑集合是離散的（7.7、12.7、13、20、30、40、127 mm），沒有任何一挺槍
 * 卡在門檻附近 —— 那個懸崖永遠不會被看到，而硬門檻講得清楚：機槍打不穿
 * 主力艦的裝甲帶。
 *
 * 【為什麼不是免傷】無敵會讓玩家找不到回饋。穿不了的那一發仍然扣一點，
 * 六百發打中六萬血的航母只扣 600 —— 實質免疫，但打得動。
 *
 * 【它只屬於子彈】炸彈的爆風與魚雷沒有口徑可言，那兩條路不進這裡。
 */

/** 打不穿時的單發傷害。**免疫要有底線，否則玩家看不到任何回饋。** */
export const NO_PENETRATION_DAMAGE = 1

/**
 * 飛機的裝甲，mm。**目前沒有機種帶裝甲。**
 *
 * 【為什麼是一個具名的 0 而不是在呼叫端寫 0】它是資料不是省略。哪天要做
 * 一台裝甲攻擊機，改的是機種表；這一格會變成 `spec.armour`，而結算那一行
 * 一個字都不用動。
 *
 * 【為什麼現在不加到機種表】九個機種都填 0 是九處沒有內容的資料，而飛機
 * 之間的耐打差異已經由 `protection` 那個除數表達了。
 */
export const AIRCRAFT_ARMOUR = 0

/**
 * 甲板上的防空砲位的裝甲，mm。**露天砲座，沒有裝甲。**
 *
 * 這一格是掃射軍艦仍然有意義的原因：艦體擋得住機槍，砲位擋不住。
 */
export const SHIP_GUN_ARMOUR = 0

/**
 * 這一發實際扣多少。
 *
 * @param damage  這一發的原始傷害
 * @param caliber 這一發的口徑，mm
 * @param armour  目標這一個部位的裝甲，mm。**0 = 沒有裝甲**
 */
export function penetrationDamage(damage: number, caliber: number, armour: number): number {
  if (caliber >= armour) return damage
  // 【取小的】穿不了的那一發不該比穿得過的還痛
  return Math.min(damage, NO_PENETRATION_DAMAGE)
}
