import { Vector3 } from 'three'
import type { Battery, Mount } from './types'
import { M2_BROWNING } from './p51d'

/**
 * F4F-4 的六挺 AN/M2 .50 —— **與 P-51D／F6F-5 是同一款槍，共用同一個物件。**
 *
 * 【為什麼不另外開一份 WeaponSpec】三台裝的都是白朗寧 AN/M2 航空型：同樣的
 * 槍管長、同樣的 .50 BMG、同樣的 887 m/s 與 800 rpm。抄一份數字過來的唯一
 * 效果，是哪天有人調 M2 的傷害時只調到一部分；這裡指向同一個物件，調一次
 * 三台一起動，而且 `weapons.test.ts` 有一條把「指的是同一挺」釘住。
 *
 * 【真機上的差別在彈藥，而本模型沒有彈藥】F4F-4 每挺 **240 發**、共 1,440
 * （生產檢驗試飛報告的重量表，OVERLOAD 6 gun VF）。F4F-3 是四挺各 450 發
 * ——**總持續射擊時間反而更長**，中途島之後飛行員抗議的就是這件事。遊戲裡
 * 沒有彈藥維度，所以 F4F-4 在這裡是「白拿兩挺槍」。這是專案負責人 2026-09-06
 * 的裁決（「武器用六挺沒關係，玩起來比較有趣」），不是這裡偷偷加的。
 * 與 `weapons/bf109k4.ts` 說 MK 108「只有 65 發」是同一個缺口。
 */

/**
 * 六挺翼槍的槍口位置，**機體座標**。
 *
 * ── 展向站位 ────────────────────────────────────────────────
 *
 * 【硬的那一半：摺翼鉸鏈由收翼全寬反解，落在 x ≈ 1.74】F4F-4 與 F6F 同樣是
 * Sto-Wing 折疊，收翼後全寬 14 ft 4 in = 4.37 m。用 F6F 那一輪量到的關係
 * （鉸鏈間距 + 兩側外翼各再突出約 0.45 m）反解：
 *
 *     2h + 2 × 0.45 = 4.37   →   h = 1.74
 *
 * 對照 F6F：2 × 2.00 + 2 × 0.47 = 4.93，真機 16 ft 2 in = 4.93 ✓ 同一條關係。
 *
 * 三挺槍**一定在鉸鏈外側**（摺翼肋與鉸鏈佔掉內側），所以 x > 1.74。
 *
 * 【軟的那一半：槍位間距 0.38 m 是從 P-51D 借來的】找不到 F4F 的槍位站位圖。
 * 借的是**同一款槍的同一種安裝**：P-51D 那三對量到的間距是 0.38 m，那是
 * AN/M2 加供彈道與彈箱在翼盒裡一個槍艙的實際寬度，換一台飛機不會變。於是
 *
 *     1.98 = 鉸鏈 1.74 + 0.24（摺翼肋與鉸鏈，沿用 F6F 量到的值）
 *     2.36 = 1.98 + 0.38
 *     2.74 = 2.36 + 0.38
 *
 * **這是本檔案最弱的一組數字**，弱在那 0.24、那 0.45、與「間距可以借」三個
 * 假設上。它影響的是曳光彈從哪裡冒出來與翼槍的散佈，不影響任何史實驗收值。
 *
 * ── 縱向：三挺前後交錯 ──────────────────────────────────────
 *
 * 與 F6F 同一種安裝：內側最前、外側縮在與前緣齊平的滅焰管裡。前緣線由自家
 * GLB 的機翼站位量到是 `LE(x) = 0.582 − 0.0456 (x − 1.85)`（Blender 系），
 * 槍口再往前伸 0.25 / 0.12 / 0.00 m。
 *
 * y 取該站位的**弦線高度**（前緣點就在弦線上）：翼根 0.067、翼尖 0.374，
 * 上反給 0.0653/m。
 *
 * 【為什麼寫死而不是 import 造型檔】`weapons/` 不該相依 `render/`，與
 * `weapons/p51d.ts`、`weapons/f6f5.ts` 同一條理由。`test/unit/hitbox.test.ts`
 * 有一條跨模組測試守住「每個槍口都在自己的機翼命中盒內」。
 */
const STATIONS: readonly (readonly [number, number, number])[] = [
  [1.98, 0.138, -0.83],
  [2.36, 0.163, -0.68],
  [2.74, 0.188, -0.54],
]

const MOUNTS: Mount[] = []
for (const [x, y, z] of STATIONS) {
  MOUNTS.push({ weapon: M2_BROWNING, position: new Vector3(x, y, z) })
  MOUNTS.push({ weapon: M2_BROWNING, position: new Vector3(-x, y, z) })
}

export const F4F4_BATTERY: Battery = {
  mounts: MOUNTS,
  /**
   * 【跟 P-51D／F6F-5 一樣的 1,000 m，而且這是刻意的】海軍當年的校射距離
   * 比這短得多。這裡不照史實，因為 1,000 m 是專案負責人在 M10 驗收時對
   * **翼槍**下的裁決（見 `weapons/p51d.ts`）—— 三台同樣是六挺 .50 的翼槍機，
   * 匯聚距離不同就等於偷偷改了平衡。要改的話三台一起改。
   */
  convergence: 1000,
  sight: M2_BROWNING,
}
