/**
 * 難度參數。
 *
 * 【M4 交付的是天花板】兩個欄位都是 0，也就是「零延遲、零瞄準誤差」。
 * 專案負責人的理由：**不可能從一個沒量過的天花板往下調難度**。M5 起以此
 * 為基準把 AI 調鈍（spec §10）。
 *
 * 【視野盲區不在此列】它需要「最後已知位置 + 搜索行為」，是一整套行為而
 * 不是一個參數。明確延後，記在 spec §2 以免被當成遺漏。
 *
 * 【`aimError` 仍然沒有人讀】`reactionDelay` 在 2026-08-06 接上了
 * （`ai/delay.ts`），`aimError` 沒有。它是另一個旋鈕，沒有量測需求驅動，
 * 刻意不做——寫在這裡以免被當成遺漏。
 */
export interface DifficultyProfile {
  /**
   * 反應延遲，秒。由 `AiController` 交給 `CommandDelay`，延後的是**輸出
   * 指令**（一個 Vector3 加三個純量），不是態勢。安全層排在延遲之後。
   */
  reactionDelay: number
  /** 瞄準誤差，rad。**目前沒有任何一處讀它** */
  aimError: number
  /**
   * 穩態補償器的時間常數，s；省略或 `<= 0` 關閉（實驗中，尚未定值）。
   * 把「新鮮 − 延遲」指令差低通後補回輸出，讓純延遲對等速動作的永久
   * 穩態誤差在 2~3τ 內收斂歸零，而突變仍吃滿 `reactionDelay` 的欺敵
   * 窗口。詳見 `CommandDelay.push`。
   */
  trimTau?: number
}

/** 王牌：M4 的唯一設定，也是全部 AI 測試與 `bench/` 的基準。 */
export const ACE: DifficultyProfile = { reactionDelay: 0, aimError: 0 }

/**
 * 遊戲預設的敵人。`DEFAULT_BATTLE` 仍然是 `ACE`，這一顆由
 * `battleConfigFrom`（`battle/skirmish.ts`）餵給實際開打的那一局。
 *
 * 【0.30 s 是怎麼選出來的】同機種 P-51D 1v1、12 種開局、每個開局把延遲
 * 換邊各跑一次（共 24 場）、每場 300 秒。延遲方 vs 零延遲方：
 *
 * ```
 * 延遲    零延遲方勝    延遲方勝   平手   觸地   平均秒數
 * 0.00     12 (50%)        12       0      0       65
 * 0.15     16 (67%)         8       0      1       84
 * 0.20     18 (75%)         6       0      2      110
 * 0.30     14 (70%)         6       4      0      133
 * 0.40     13 (59%)         9       2      1      124
 * 0.50     14 (67%)         7       3      0      143
 * ```
 *
 * 0.00 那一列剛好 12:12，證明這個測法本身沒有偏向。
 *
 * 【為什麼不是勝率最高的 0.20】**0.15~0.50 之間分不出來。** 每列只有 24 場，
 * 二項分布在 p=0.5 的標準差就有 10%，所以 59% 與 75% 差不到 1.5σ。能斷言的
 * 只有聚合值：五列合計 75:36（67.6%），那個確實顯著。
 *
 * 於是改用第二個判準——**欺敵動作的窗口什麼時候打開**。同一組受控場景量
 * 異平面破防的被鎖定佔比：150 ms 是 86%（幾乎沒用），300 ms 掉到 16%，
 * 500 ms 是 7.8%。窗口在 300 ms 才真的開，而做這件事的初衷就是讓那些動作
 * 有意義。
 *
 * 第三個佐證是史實：受過訓練的飛行員對已辨識情境的視覺反應約 0.25~0.40 s。
 *
 * 【單調上升的只有戰鬥長度】65 s → 133 s。延遲讓 AI 咬得住但殺不掉，那是
 * 這個旋鈕最穩定的效果，也是 `ai-reaction-delay.test.ts` 拿來當門檻的量。
 */
/*
 * 【`trimTau: 1` 的定值依據（2026-08-24，專案負責人裁定）】純延遲對可預測
 * 運動有永久穩態誤差：靶機 700 m 等距橫飛 15°/s 時恆差 8~9°，永遠進不了
 * 3° 開火錐——真人追蹤規律動作會靠預測補掉，只有突變才吃反應延遲。
 * 補償器（`CommandDelay.push` 的 trim）把「比 τ 慢的動作看穿、比 τ 快的
 * 動作照騙」。band-drill 的 orbit／weave 兩局實測（機首離預瞄點）：
 *
 * ```
 *          orbit 等速繞圈    weave S 繞 6 s 週期（峰值）
 * 純延遲     6~9° 錐外        5~7°
 * τ=1        1~3° ≈ACE       3~4°（慢 S 繞被學走一半）
 * τ=2        2~4° 錐緣        4~6°
 * ACE        1~5°             3~4°
 * ```
 *
 * 取 1：繞圈追平 ACE 的咬環能力；代價是 6 s 級的慢 S 繞欺敵折半，更快的
 * 假動作（2~3 s 換邊）衰減比例平方成長、照樣騙得到。
 */
export const VETERAN: DifficultyProfile = { reactionDelay: 0.3, aimError: 0, trimTau: 1 }
